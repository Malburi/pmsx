-- 교육관리시스템(ED) 샘플 DDL (Oracle) — FK 미선언 (추정 관계 검증용)
CREATE TABLE TB_DEPT (
    DEPT_CD VARCHAR2(10) NOT NULL, DEPT_NM VARCHAR2(100) NOT NULL, USE_YN CHAR(1) DEFAULT 'Y',
    CONSTRAINT PK_TB_DEPT PRIMARY KEY (DEPT_CD)
);
COMMENT ON TABLE TB_DEPT IS '부서';
CREATE TABLE TB_EMP (
    EMP_NO VARCHAR2(10) NOT NULL, EMP_NM VARCHAR2(50) NOT NULL, DEPT_CD VARCHAR2(10),
    CONSTRAINT PK_TB_EMP PRIMARY KEY (EMP_NO)
);
COMMENT ON TABLE TB_EMP IS '사원';
CREATE TABLE TB_EDU_COURSE (
    COURSE_ID VARCHAR2(20) NOT NULL, COURSE_NM VARCHAR2(200) NOT NULL, EDU_YEAR VARCHAR2(4),
    START_DT DATE, END_DT DATE, CAPACITY NUMBER(5), DEPT_CD VARCHAR2(10),
    CONSTRAINT PK_TB_EDU_COURSE PRIMARY KEY (COURSE_ID)
);
COMMENT ON TABLE TB_EDU_COURSE IS '교육과정';
CREATE TABLE TB_EDU_APPLY (
    APPLY_ID NUMBER(15) NOT NULL, COURSE_ID VARCHAR2(20) NOT NULL, EMP_NO VARCHAR2(10) NOT NULL,
    STATUS VARCHAR2(10), REG_DT DATE,
    CONSTRAINT PK_TB_EDU_APPLY PRIMARY KEY (APPLY_ID)
);
COMMENT ON TABLE TB_EDU_APPLY IS '수강신청';
CREATE TABLE TB_CERT (
    CERT_ID NUMBER(15) NOT NULL, CERT_NM VARCHAR2(200) NOT NULL, ISSUER VARCHAR2(200), ACQ_DT DATE, EMP_NO VARCHAR2(10),
    CONSTRAINT PK_TB_CERT PRIMARY KEY (CERT_ID)
);
COMMENT ON TABLE TB_CERT IS '자격증';
