-- 샘플 근태(AT) — Oracle. FK 없음 (추정 관계 검증)
CREATE TABLE TB_EMP (
    EMP_NO   VARCHAR2(10) PRIMARY KEY,
    EMP_NM   VARCHAR2(50) NOT NULL,
    DEPT_CD  VARCHAR2(10)
);
CREATE TABLE TB_CODE (
    GRP_CD   VARCHAR2(20) NOT NULL,
    CODE     VARCHAR2(20) NOT NULL,
    CODE_NM  VARCHAR2(100),
    SORT_ORD NUMBER(4),
    CONSTRAINT PK_TB_CODE PRIMARY KEY (GRP_CD, CODE)
);
CREATE TABLE TB_ATT_REQ (
    REQ_NO   NUMBER(10) PRIMARY KEY,
    EMP_NO   VARCHAR2(10) NOT NULL,
    ATT_TYPE VARCHAR2(10),
    REQ_DT   DATE,
    REASON   VARCHAR2(200),
    STATUS   VARCHAR2(10)
);
CREATE TABLE TB_ATT_APPR (
    REQ_NO      NUMBER(10) PRIMARY KEY,
    APPR_STATUS VARCHAR2(10),
    REQ_TM      DATE,
    APPR_TM     DATE
);
COMMENT ON TABLE TB_ATT_REQ IS '근태신청';
COMMENT ON TABLE TB_ATT_APPR IS '근태결재';
