-- =============================================================
-- 인사시스템(HR) 테이블 정의 - Oracle 11g
-- 주의: 운영 이관 당시 일부 FK 미생성 (TB_EMP.DEPT_CD, TB_APPOINT.*)
-- =============================================================

CREATE TABLE TB_DEPT (
    DEPT_CD      VARCHAR2(10)   NOT NULL,
    DEPT_NM      VARCHAR2(100)  NOT NULL,
    UP_DEPT_CD   VARCHAR2(10),
    SORT_ORD     NUMBER(5)      DEFAULT 0,
    USE_YN       CHAR(1)        DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_TB_DEPT PRIMARY KEY (DEPT_CD)
);
COMMENT ON TABLE TB_DEPT IS '부서';
COMMENT ON COLUMN TB_DEPT.DEPT_CD IS '부서코드';
COMMENT ON COLUMN TB_DEPT.DEPT_NM IS '부서명';
COMMENT ON COLUMN TB_DEPT.UP_DEPT_CD IS '상위부서코드';
COMMENT ON COLUMN TB_DEPT.SORT_ORD IS '정렬순서';
COMMENT ON COLUMN TB_DEPT.USE_YN IS '사용여부';

CREATE TABLE TB_EMP (
    EMP_NO       VARCHAR2(8)    NOT NULL,
    EMP_NM       VARCHAR2(50)   NOT NULL,
    DEPT_CD      VARCHAR2(10)   NOT NULL,
    POS_CD       VARCHAR2(10),
    HIRE_DT      CHAR(8),
    EMAIL        VARCHAR2(100),
    USE_YN       CHAR(1)        DEFAULT 'Y' NOT NULL,
    REG_DT       DATE           DEFAULT SYSDATE,
    REG_ID       VARCHAR2(20),
    UPD_DT       DATE,
    UPD_ID       VARCHAR2(20),
    CONSTRAINT PK_TB_EMP PRIMARY KEY (EMP_NO)
);
COMMENT ON TABLE TB_EMP IS '사원';
COMMENT ON COLUMN TB_EMP.EMP_NO IS '사원번호';
COMMENT ON COLUMN TB_EMP.EMP_NM IS '사원명';
COMMENT ON COLUMN TB_EMP.DEPT_CD IS '부서코드';
COMMENT ON COLUMN TB_EMP.POS_CD IS '직위코드';
COMMENT ON COLUMN TB_EMP.HIRE_DT IS '입사일자';
COMMENT ON COLUMN TB_EMP.EMAIL IS '이메일';
COMMENT ON COLUMN TB_EMP.USE_YN IS '사용여부';

CREATE TABLE TB_EMP_HIST (
    HIST_SEQ     NUMBER(12)     NOT NULL,
    EMP_NO       VARCHAR2(8)    NOT NULL,
    CHG_DT       DATE           NOT NULL,
    CHG_ID       VARCHAR2(20),
    CHG_TYPE     CHAR(1),
    BEFORE_JSON  VARCHAR2(4000),
    CONSTRAINT PK_TB_EMP_HIST PRIMARY KEY (HIST_SEQ),
    CONSTRAINT FK_TB_EMP_HIST_01 FOREIGN KEY (EMP_NO) REFERENCES TB_EMP (EMP_NO)
);
COMMENT ON TABLE TB_EMP_HIST IS '사원변경이력';
COMMENT ON COLUMN TB_EMP_HIST.CHG_TYPE IS '변경구분(I/U/D/A)';

CREATE TABLE TB_APPOINT (
    APPT_NO      VARCHAR2(10)   NOT NULL,
    EMP_NO       VARCHAR2(8)    NOT NULL,
    APPT_TYPE    VARCHAR2(10)   NOT NULL,
    FROM_DEPT_CD VARCHAR2(10),
    TO_DEPT_CD   VARCHAR2(10),
    APPT_DT      CHAR(8)        NOT NULL,
    STATUS       CHAR(1)        DEFAULT 'R',
    REG_DT       DATE           DEFAULT SYSDATE,
    REG_ID       VARCHAR2(20),
    CONSTRAINT PK_TB_APPOINT PRIMARY KEY (APPT_NO)
);
COMMENT ON TABLE TB_APPOINT IS '인사발령';
COMMENT ON COLUMN TB_APPOINT.APPT_TYPE IS '발령유형';
COMMENT ON COLUMN TB_APPOINT.STATUS IS '상태(R:등록,C:확정)';

CREATE TABLE TB_CODE (
    GRP_CD       VARCHAR2(10)   NOT NULL,
    CD           VARCHAR2(10)   NOT NULL,
    CD_NM        VARCHAR2(100)  NOT NULL,
    SORT_ORD     NUMBER(5)      DEFAULT 0,
    USE_YN       CHAR(1)        DEFAULT 'Y',
    CONSTRAINT PK_TB_CODE PRIMARY KEY (GRP_CD, CD)
);
COMMENT ON TABLE TB_CODE IS '공통코드';

CREATE TABLE TB_MENU (
    MENU_ID      VARCHAR2(10)   NOT NULL,
    UP_MENU_ID   VARCHAR2(10),
    MENU_NM      VARCHAR2(100)  NOT NULL,
    MENU_URL     VARCHAR2(200),
    SORT_ORD     NUMBER(5),
    SYS_CD       VARCHAR2(10)   NOT NULL,
    CONSTRAINT PK_TB_MENU PRIMARY KEY (MENU_ID)
);
COMMENT ON TABLE TB_MENU IS '메뉴';

CREATE SEQUENCE SEQ_EMP_NO START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_EMP_HIST START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_APPT_NO START WITH 1 INCREMENT BY 1;

-- 2024.03 교육이력 (FK 미생성)
CREATE TABLE TB_EDU_HIST (
    EDU_SEQ      NUMBER(12)     NOT NULL,
    EMP_NO       VARCHAR2(8)    NOT NULL,
    EDU_TYPE_CD  VARCHAR2(10)   NOT NULL,
    EDU_NM       VARCHAR2(200)  NOT NULL,
    EDU_YEAR     CHAR(4)        NOT NULL,
    EDU_HOURS    NUMBER(5)      DEFAULT 0,
    INST_NM      VARCHAR2(100),
    USE_YN       CHAR(1)        DEFAULT 'Y' NOT NULL,
    REG_DT       DATE           DEFAULT SYSDATE,
    REG_ID       VARCHAR2(20),
    CONSTRAINT PK_TB_EDU_HIST PRIMARY KEY (EDU_SEQ)
);
COMMENT ON TABLE TB_EDU_HIST IS '교육이력';
COMMENT ON COLUMN TB_EDU_HIST.EDU_TYPE_CD IS '교육구분코드(EDU)';
COMMENT ON COLUMN TB_EDU_HIST.EDU_YEAR IS '교육연도';
COMMENT ON COLUMN TB_EDU_HIST.EDU_HOURS IS '이수시간';
