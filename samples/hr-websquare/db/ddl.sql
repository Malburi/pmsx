-- 샘플 복리후생(BW) — Oracle. FK 는 일부만 (추정 관계 검증)
CREATE TABLE TB_DEPT (
    DEPT_CD   VARCHAR2(10) PRIMARY KEY,
    DEPT_NM   VARCHAR2(50) NOT NULL
);
CREATE TABLE TB_EMP (
    EMP_NO    VARCHAR2(10) PRIMARY KEY,
    EMP_NM    VARCHAR2(50) NOT NULL,
    DEPT_CD   VARCHAR2(10),
    GRADE_CD  VARCHAR2(10)
);
CREATE TABLE TB_CODE (
    GRP_CD    VARCHAR2(20) NOT NULL,
    CODE      VARCHAR2(20) NOT NULL,
    CODE_NM   VARCHAR2(100),
    SORT_ORD  NUMBER(4),
    USE_YN    CHAR(1) DEFAULT 'Y',
    CONSTRAINT PK_TB_CODE PRIMARY KEY (GRP_CD, CODE)
);
CREATE TABLE TB_WELFARE_REQ (
    REQ_NO    NUMBER(10) PRIMARY KEY,
    EMP_NO    VARCHAR2(10) NOT NULL,
    REQ_TYPE  VARCHAR2(10),
    REQ_AMT   NUMBER(12),
    STATUS    VARCHAR2(10),
    REQ_DT    DATE,
    UPD_DT    DATE
);
CREATE TABLE TB_WELFARE_REQ_HIST (
    REQ_NO    NUMBER(10) NOT NULL,
    CHG_DT    DATE NOT NULL,
    ROW_STATUS CHAR(1),
    REQ_AMT   NUMBER(12),
    CONSTRAINT FK_WREQ_HIST FOREIGN KEY (REQ_NO) REFERENCES TB_WELFARE_REQ (REQ_NO)
);
CREATE TABLE TB_WELFARE_STD (
    STD_YEAR   CHAR(4) NOT NULL,
    GRADE_CD   VARCHAR2(10) NOT NULL,
    BASE_POINT NUMBER(8),
    ADD_POINT  NUMBER(8),
    CONSTRAINT PK_TB_WELFARE_STD PRIMARY KEY (STD_YEAR, GRADE_CD)
);
CREATE TABLE TB_WELFARE_LIMIT (
    STD_YEAR   CHAR(4) NOT NULL,
    REQ_TYPE   VARCHAR2(10) NOT NULL,
    LIMIT_AMT  NUMBER(12),
    CONSTRAINT PK_TB_WELFARE_LIMIT PRIMARY KEY (STD_YEAR, REQ_TYPE)
);
COMMENT ON TABLE TB_WELFARE_REQ IS '복지포인트 신청';
COMMENT ON TABLE TB_WELFARE_STD IS '복지포인트 지급기준';

CREATE OR REPLACE PROCEDURE SP_WELFARE_COPY_YEAR (P_YEAR IN CHAR) IS
BEGIN
    INSERT INTO TB_WELFARE_STD (STD_YEAR, GRADE_CD, BASE_POINT, ADD_POINT)
    SELECT P_YEAR, GRADE_CD, BASE_POINT, ADD_POINT FROM TB_WELFARE_STD WHERE STD_YEAR = TO_CHAR(TO_NUMBER(P_YEAR) - 1);
    INSERT INTO TB_WELFARE_LIMIT (STD_YEAR, REQ_TYPE, LIMIT_AMT)
    SELECT P_YEAR, REQ_TYPE, LIMIT_AMT FROM TB_WELFARE_LIMIT WHERE STD_YEAR = TO_CHAR(TO_NUMBER(P_YEAR) - 1);
END;
