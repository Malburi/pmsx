-- 샘플 채용관리(RC) — MSSQL(T-SQL). TB_RECRUIT.DEPT_CD, TB_APPLICANT.RECRUIT_NO 는 FK 없음 (추정 관계 검증)
CREATE TABLE dbo.TB_DEPT (
    DEPT_CD   VARCHAR(10)   NOT NULL PRIMARY KEY,
    DEPT_NM   NVARCHAR(50)  NOT NULL
);
CREATE TABLE dbo.TB_RECRUIT (
    RECRUIT_NO VARCHAR(20)   NOT NULL PRIMARY KEY,
    TITLE      NVARCHAR(200) NOT NULL,
    DEPT_CD    VARCHAR(10)   NULL,
    END_DT     DATE          NULL,
    CONTENT    NVARCHAR(MAX) NULL,
    STATUS     VARCHAR(10)   DEFAULT 'OPEN',
    UPD_DT     DATETIME      NULL
);
CREATE TABLE dbo.TB_APPLICANT (
    APPLICANT_ID INT           IDENTITY(1,1) PRIMARY KEY,
    RECRUIT_NO   VARCHAR(20)   NOT NULL,
    APPLICANT_NM NVARCHAR(50)  NOT NULL,
    EMAIL        VARCHAR(100)  NULL,
    STATUS       VARCHAR(10)   DEFAULT 'APPLY'
);
CREATE TABLE dbo.TB_APPLICANT_HIST (
    HIST_SEQ     INT           IDENTITY(1,1) PRIMARY KEY,
    APPLICANT_ID INT           NOT NULL,
    STATUS       VARCHAR(10)   NOT NULL,
    CHG_DT       DATETIME      NOT NULL,
    CONSTRAINT FK_APPL_HIST FOREIGN KEY (APPLICANT_ID) REFERENCES dbo.TB_APPLICANT (APPLICANT_ID)
);
GO

CREATE PROCEDURE dbo.USP_RECRUIT_SAVE
    @RECRUIT_NO VARCHAR(20), @TITLE NVARCHAR(200), @DEPT_CD VARCHAR(10), @END_DT DATE, @CONTENT NVARCHAR(MAX)
AS
BEGIN
    IF @RECRUIT_NO IS NULL
        INSERT INTO dbo.TB_RECRUIT (RECRUIT_NO, TITLE, DEPT_CD, END_DT, CONTENT, STATUS)
        VALUES (CONVERT(VARCHAR(8), GETDATE(), 112) + '-' + CAST(NEXT VALUE FOR dbo.SEQ_RECRUIT AS VARCHAR), @TITLE, @DEPT_CD, @END_DT, @CONTENT, 'OPEN')
    ELSE
        UPDATE dbo.TB_RECRUIT SET TITLE = @TITLE, DEPT_CD = @DEPT_CD, END_DT = @END_DT, CONTENT = @CONTENT, UPD_DT = GETDATE()
         WHERE RECRUIT_NO = @RECRUIT_NO
END
GO

CREATE PROCEDURE dbo.USP_APPLICANT_INSERT
    @Name NVARCHAR(50), @Email VARCHAR(100), @RecruitNo VARCHAR(20)
AS
BEGIN
    INSERT INTO dbo.TB_APPLICANT (RECRUIT_NO, APPLICANT_NM, EMAIL, STATUS) VALUES (@RecruitNo, @Name, @Email, 'APPLY')
END
GO
