-- 급여시스템(PY) 샘플 DDL (Oracle) — FK 는 일부만 선언 (추정 관계 검증용)

CREATE TABLE TB_DEPT (
    DEPT_CD     VARCHAR2(10)    NOT NULL,
    DEPT_NM     VARCHAR2(100)   NOT NULL,
    SORT_ORD    NUMBER(5),
    USE_YN      CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_TB_DEPT PRIMARY KEY (DEPT_CD)
);
COMMENT ON TABLE TB_DEPT IS '부서';

CREATE TABLE TB_EMP (
    EMP_NO      VARCHAR2(10)    NOT NULL,
    EMP_NM      VARCHAR2(50)    NOT NULL,
    DEPT_CD     VARCHAR2(10),
    HIRE_DT     DATE,
    USE_YN      CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_TB_EMP PRIMARY KEY (EMP_NO)
);
COMMENT ON TABLE TB_EMP IS '사원';

CREATE TABLE TB_CODE (
    GRP_CD      VARCHAR2(20)    NOT NULL,
    CD          VARCHAR2(20)    NOT NULL,
    CD_NM       VARCHAR2(100)   NOT NULL,
    SORT_ORD    NUMBER(5),
    CONSTRAINT PK_TB_CODE PRIMARY KEY (GRP_CD, CD)
);
COMMENT ON TABLE TB_CODE IS '공통코드';

CREATE TABLE TB_PAY_CALC (
    PAY_YM      VARCHAR2(6)     NOT NULL,
    EMP_NO      VARCHAR2(10)    NOT NULL,
    BASE_AMT    NUMBER(15)      DEFAULT 0,
    ALLOW_AMT   NUMBER(15)      DEFAULT 0,
    DEDUCT_AMT  NUMBER(15)      DEFAULT 0,
    CLOSE_YN    CHAR(1)         DEFAULT 'N',
    UPD_ID      VARCHAR2(20),
    UPD_DT      DATE,
    CONSTRAINT PK_TB_PAY_CALC PRIMARY KEY (PAY_YM, EMP_NO),
    CONSTRAINT FK_TB_PAY_CALC_01 FOREIGN KEY (EMP_NO) REFERENCES TB_EMP (EMP_NO)
);
COMMENT ON TABLE TB_PAY_CALC IS '급여계산';
COMMENT ON COLUMN TB_PAY_CALC.PAY_YM IS '귀속년월';

CREATE TABLE TB_ALLOW (
    ALLOW_CD    VARCHAR2(10)    NOT NULL,
    ALLOW_NM    VARCHAR2(100)   NOT NULL,
    ALLOW_TYPE  VARCHAR2(10),
    BASE_AMT    NUMBER(15),
    USE_YN      CHAR(1)         DEFAULT 'Y',
    REG_DT      DATE,
    CONSTRAINT PK_TB_ALLOW PRIMARY KEY (ALLOW_CD)
);
COMMENT ON TABLE TB_ALLOW IS '수당';

CREATE TABLE TB_ALLOW_HIST (
    ALLOW_CD    VARCHAR2(10)    NOT NULL,
    CHG_DT      DATE            NOT NULL,
    ROW_TYPE    VARCHAR2(1),
    BASE_AMT    NUMBER(15),
    CONSTRAINT PK_TB_ALLOW_HIST PRIMARY KEY (ALLOW_CD, CHG_DT)
);
COMMENT ON TABLE TB_ALLOW_HIST IS '수당 변경이력';

CREATE TABLE TB_PAY_ITEM (
    PAY_YM      VARCHAR2(6)     NOT NULL,
    EMP_NO      VARCHAR2(10)    NOT NULL,
    ITEM_TYPE   CHAR(1)         NOT NULL,
    ITEM_CD     VARCHAR2(10)    NOT NULL,
    AMT         NUMBER(15),
    RMK         VARCHAR2(200),
    CONSTRAINT PK_TB_PAY_ITEM PRIMARY KEY (PAY_YM, EMP_NO, ITEM_TYPE, ITEM_CD)
);
COMMENT ON TABLE TB_PAY_ITEM IS '급여항목';

CREATE TABLE TB_TAX_RATE (
    TAX_YEAR    VARCHAR2(4)     NOT NULL,
    FROM_AMT    NUMBER(15)      NOT NULL,
    TO_AMT      NUMBER(15),
    RATE        NUMBER(5,2),
    CONSTRAINT PK_TB_TAX_RATE PRIMARY KEY (TAX_YEAR, FROM_AMT)
);
COMMENT ON TABLE TB_TAX_RATE IS '세율';

CREATE TABLE TB_PAY_CLOSE_HIST (
    PAY_YM      VARCHAR2(6)     NOT NULL,
    CLOSE_DT    DATE            NOT NULL,
    CLOSE_ID    VARCHAR2(20),
    CONSTRAINT PK_TB_PAY_CLOSE_HIST PRIMARY KEY (PAY_YM, CLOSE_DT)
);
COMMENT ON TABLE TB_PAY_CLOSE_HIST IS '급여마감 이력';

CREATE TABLE TB_MAIL_QUEUE (
    MAIL_ID     NUMBER(15)      NOT NULL,
    EMP_NO      VARCHAR2(10),
    MAIL_TYPE   VARCHAR2(20),
    REG_DT      DATE,
    CONSTRAINT PK_TB_MAIL_QUEUE PRIMARY KEY (MAIL_ID)
);
COMMENT ON TABLE TB_MAIL_QUEUE IS '메일 발송 대기열';
