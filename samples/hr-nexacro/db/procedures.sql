-- 급여계산 프로시저 (PL/SQL) — SP → SP 호출 포함

CREATE OR REPLACE PROCEDURE SP_PAY_CALC (
    P_PAY_YM   IN VARCHAR2,
    P_USER_ID  IN VARCHAR2
) AS
    V_CNT NUMBER;
BEGIN
    -- 대상자 기본급 반영
    MERGE INTO TB_PAY_CALC C
    USING (SELECT EMP_NO FROM TB_EMP WHERE USE_YN = 'Y') E
       ON (C.PAY_YM = P_PAY_YM AND C.EMP_NO = E.EMP_NO)
     WHEN NOT MATCHED THEN
          INSERT (PAY_YM, EMP_NO, BASE_AMT, UPD_ID, UPD_DT) VALUES (P_PAY_YM, E.EMP_NO, 0, P_USER_ID, SYSDATE);

    -- 수당 항목 생성
    INSERT INTO TB_PAY_ITEM (PAY_YM, EMP_NO, ITEM_TYPE, ITEM_CD, AMT)
    SELECT C.PAY_YM, C.EMP_NO, 'A', A.ALLOW_CD, A.BASE_AMT
      FROM TB_PAY_CALC C, TB_ALLOW A
     WHERE C.PAY_YM = P_PAY_YM
       AND A.USE_YN = 'Y';

    UPDATE TB_PAY_CALC C
       SET ALLOW_AMT = (SELECT NVL(SUM(I.AMT), 0) FROM TB_PAY_ITEM I
                         WHERE I.PAY_YM = C.PAY_YM AND I.EMP_NO = C.EMP_NO AND I.ITEM_TYPE = 'A')
     WHERE C.PAY_YM = P_PAY_YM;

    -- 세금 계산
    SP_PAY_TAX(P_PAY_YM);

    SELECT COUNT(*) INTO V_CNT FROM TB_PAY_CALC WHERE PAY_YM = P_PAY_YM;
EXCEPTION
    WHEN OTHERS THEN
        RAISE;
END SP_PAY_CALC;
/

CREATE OR REPLACE PROCEDURE SP_PAY_TAX (
    P_PAY_YM   IN VARCHAR2
) AS
BEGIN
    INSERT INTO TB_PAY_ITEM (PAY_YM, EMP_NO, ITEM_TYPE, ITEM_CD, AMT)
    SELECT C.PAY_YM, C.EMP_NO, 'D', 'TAX', ROUND((C.BASE_AMT + C.ALLOW_AMT) * R.RATE / 100)
      FROM TB_PAY_CALC C
      JOIN TB_TAX_RATE R ON R.TAX_YEAR = SUBSTR(C.PAY_YM, 1, 4)
                        AND C.BASE_AMT + C.ALLOW_AMT BETWEEN R.FROM_AMT AND NVL(R.TO_AMT, 999999999999)
     WHERE C.PAY_YM = P_PAY_YM;

    UPDATE TB_PAY_CALC C
       SET DEDUCT_AMT = (SELECT NVL(SUM(I.AMT), 0) FROM TB_PAY_ITEM I
                          WHERE I.PAY_YM = C.PAY_YM AND I.EMP_NO = C.EMP_NO AND I.ITEM_TYPE = 'D')
     WHERE C.PAY_YM = P_PAY_YM;

    PKG_PAY_LOG.WRITE_LOG('TAX', P_PAY_YM);
END SP_PAY_TAX;
/
