-- 자동 생성: tools/ddl/convert_ddl.py ← common/V5__r3_sm.sql (mssql). 직접 고치지 말고 생성기를 고칠 것.
-- PMS-X R3: SM 운영 (SR·SLA·장애·문제·변경·정기 작업·운영 자산·KB·월간 운영보고) (docs/13 명세)

-- ───────── SLA 정책 ─────────
CREATE TABLE SM_SLA_POLICY (
    POLICY_ID          NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID         NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME               NVARCHAR(200) NOT NULL,
    TYPES              NVARCHAR(200),                 -- 콤마 구분, 비면 전체
    PRIORITIES         NVARCHAR(50),                  -- 콤마 구분, 비면 전체
    RESPONSE_MIN       INT      NOT NULL,
    RESOLVE_MIN        INT      NOT NULL,
    BH_START           NVARCHAR(5)   DEFAULT '09:00' NOT NULL,
    BH_END             NVARCHAR(5)   DEFAULT '18:00' NOT NULL,
    BH_DAYS            NVARCHAR(20)  DEFAULT '1,2,3,4,5' NOT NULL,   -- ISO 요일 1=월 … 7=일
    TWENTY_FOUR_SEVEN  ${bit} DEFAULT 0 NOT NULL,
    ORD                INT DEFAULT 0 NOT NULL,
    CREATED_AT         ${tstz} NOT NULL,
    UPDATED_AT         ${tstz}
);
CREATE INDEX IX_SM_SLA_POLICY_PROJECT ON SM_SLA_POLICY (PROJECT_ID, ORD);

-- ───────── SR ─────────
CREATE TABLE SM_SR (
    SR_ID          NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID     NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    SR_NO          NVARCHAR(30)  NOT NULL,
    TYPE           NVARCHAR(10)  NOT NULL,
    PRIORITY       NVARCHAR(2)   NOT NULL,
    TITLE          NVARCHAR(300) NOT NULL,
    DESCRIPTION    NVARCHAR(MAX),
    CHANNEL        NVARCHAR(10)  NOT NULL,
    REQ_NAME       NVARCHAR(100) NOT NULL,
    REQ_ORG        NVARCHAR(200),
    REQ_CONTACT    NVARCHAR(200),
    REQ_USER_ID    NVARCHAR(26),
    STATUS         NVARCHAR(12)  DEFAULT 'RECEIVED' NOT NULL,
    ASSIGNEE_ID    NVARCHAR(26),
    SYSTEM_ID      NVARCHAR(26),
    SCREEN_ID      NVARCHAR(26),
    ELEMENT_ID     NVARCHAR(26),
    POLICY_ID      NVARCHAR(26),
    RESPONDED_AT   ${tstz},
    RESOLVED_AT    ${tstz},
    CLOSED_AT      ${tstz},
    REJECT_REASON  NVARCHAR(1000),
    NOTIFY_FLAGS   NVARCHAR(100),                     -- SLA 알림 1회 발송 기록 (RESP_SOON,RESP_BREACH,RES_SOON,RES_BREACH)
    MESSAGE_ID     NVARCHAR(300),                     -- 메일 접수 중복 방지
    ORIGIN_DEFECT_ID NVARCHAR(26),                    -- SI→SM 인수인계로 생성된 경우 원래 결함
    CREATED_AT     ${tstz} NOT NULL,
    CREATED_BY     NVARCHAR(26),
    UPDATED_AT     ${tstz} NOT NULL,
    UPDATED_BY     NVARCHAR(26),
    CONSTRAINT UQ_SM_SR_NO UNIQUE (PROJECT_ID, SR_NO)
);
CREATE INDEX IX_SM_SR_PROJECT ON SM_SR (PROJECT_ID, STATUS);
CREATE INDEX IX_SM_SR_SCREEN ON SM_SR (SCREEN_ID);
CREATE INDEX IX_SM_SR_CREATED ON SM_SR (PROJECT_ID, CREATED_AT);
CREATE INDEX IX_SM_SR_MESSAGE ON SM_SR (MESSAGE_ID);

-- SLA 시계 이벤트 (START / PAUSE / RESUME / STOP)
CREATE TABLE SM_SLA_EVENT (
    SR_ID     NVARCHAR(26) NOT NULL,
    SEQ       INT     NOT NULL,
    EVENT     NVARCHAR(10) NOT NULL,
    EVENT_AT  ${tstz} NOT NULL,
    PRIMARY KEY (SR_ID, SEQ)
);

CREATE TABLE SM_SR_COMMENT (
    COMMENT_ID  NVARCHAR(26) PRIMARY KEY,
    SR_ID       NVARCHAR(26) NOT NULL,
    CONTENT     NVARCHAR(MAX)        NOT NULL,
    INTERNAL    ${bit} DEFAULT 0 NOT NULL,
    AUTHOR_ID   NVARCHAR(26) NOT NULL,
    CREATED_AT  ${tstz} NOT NULL
);
CREATE INDEX IX_SM_SR_COMMENT ON SM_SR_COMMENT (SR_ID, CREATED_AT);

-- ───────── 장애·문제·변경 ─────────
CREATE TABLE SM_INCIDENT (
    INCIDENT_ID   NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID    NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    INCIDENT_NO   NVARCHAR(30)  NOT NULL,
    TITLE         NVARCHAR(300) NOT NULL,
    GRADE         INT      NOT NULL,
    STATUS        NVARCHAR(10)  DEFAULT 'OPEN' NOT NULL,
    STARTED_AT    ${tstz} NOT NULL,
    DETECTED_AT   ${tstz},
    RECOVERED_AT  ${tstz},
    IMPACT        NVARCHAR(MAX),
    SYSTEM_IDS    NVARCHAR(MAX),
    CAUSE         NVARCHAR(MAX),
    RCA           NVARCHAR(MAX),
    PREVENTION    NVARCHAR(MAX),
    SR_IDS        NVARCHAR(MAX),
    CREATED_AT    ${tstz} NOT NULL,
    CREATED_BY    NVARCHAR(26),
    UPDATED_AT    ${tstz} NOT NULL,
    UPDATED_BY    NVARCHAR(26)
);
CREATE INDEX IX_SM_INCIDENT_PROJECT ON SM_INCIDENT (PROJECT_ID, STARTED_AT);

CREATE TABLE SM_INCIDENT_TIMELINE (
    ITEM_ID      NVARCHAR(26) PRIMARY KEY,
    INCIDENT_ID  NVARCHAR(26) NOT NULL,
    EVENT_AT     ${tstz} NOT NULL,
    CONTENT      NVARCHAR(2000) NOT NULL,
    CREATED_BY   NVARCHAR(26)
);
CREATE INDEX IX_SM_INCIDENT_TL ON SM_INCIDENT_TIMELINE (INCIDENT_ID, EVENT_AT);

CREATE TABLE SM_PROBLEM (
    PROBLEM_ID    NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID    NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    PROBLEM_NO    NVARCHAR(30)  NOT NULL,
    TITLE         NVARCHAR(300) NOT NULL,
    ROOT_CAUSE    NVARCHAR(MAX),
    WORKAROUND    NVARCHAR(MAX),
    KNOWN_ERROR   ${bit} DEFAULT 0 NOT NULL,
    STATUS        NVARCHAR(10)  DEFAULT 'OPEN' NOT NULL,
    SR_IDS        NVARCHAR(MAX),
    INCIDENT_IDS  NVARCHAR(MAX),
    CREATED_AT    ${tstz} NOT NULL,
    CREATED_BY    NVARCHAR(26),
    UPDATED_AT    ${tstz} NOT NULL,
    UPDATED_BY    NVARCHAR(26)
);
CREATE INDEX IX_SM_PROBLEM_PROJECT ON SM_PROBLEM (PROJECT_ID);

CREATE TABLE SM_CHANGE (
    CHANGE_ID      NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID     NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    CHANGE_NO      NVARCHAR(30)  NOT NULL,
    TITLE          NVARCHAR(300) NOT NULL,
    TYPE           NVARCHAR(10)  NOT NULL,
    RISK           NVARCHAR(1)   DEFAULT 'M' NOT NULL,
    PLAN_TXT       NVARCHAR(MAX),
    ROLLBACK_PLAN  NVARCHAR(MAX),
    SCHEDULED_AT   ${tstz},
    DEPLOYED_AT    ${tstz},
    STATUS         NVARCHAR(12)  DEFAULT 'REQUESTED' NOT NULL,
    SR_IDS         NVARCHAR(MAX),
    SCREEN_IDS     NVARCHAR(MAX),
    COMMITS        NVARCHAR(MAX),
    CREATED_AT     ${tstz} NOT NULL,
    CREATED_BY     NVARCHAR(26),
    UPDATED_AT     ${tstz} NOT NULL,
    UPDATED_BY     NVARCHAR(26)
);
CREATE INDEX IX_SM_CHANGE_PROJECT ON SM_CHANGE (PROJECT_ID, SCHEDULED_AT);

CREATE TABLE SM_CHANGE_CAB (
    CHANGE_ID    NVARCHAR(26) NOT NULL,
    USER_ID      NVARCHAR(26) NOT NULL,
    DECISION     NVARCHAR(10) NOT NULL,
    COMMENT_TXT  NVARCHAR(1000),
    DECIDED_AT   ${tstz} NOT NULL,
    PRIMARY KEY (CHANGE_ID, USER_ID)
);

-- ───────── 정기 작업·운영 자산·KB ─────────
CREATE TABLE SM_ROUTINE_JOB (
    JOB_ID          NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID      NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME            NVARCHAR(200) NOT NULL,
    FREQ            NVARCHAR(10)  NOT NULL,           -- DAILY / WEEKLY / MONTHLY
    DOW             NVARCHAR(20),                     -- WEEKLY: ISO 요일 콤마 구분
    DAY_OF_MONTH    INT,                         -- MONTHLY: 1~31 (말일 초과 시 말일)
    OWNER_ID        NVARCHAR(26),
    CHECKLIST_JSON  NVARCHAR(MAX),
    CREATED_AT      ${tstz} NOT NULL,
    UPDATED_AT      ${tstz}
);

CREATE TABLE SM_ROUTINE_CHECK (
    JOB_ID    NVARCHAR(26) NOT NULL,
    CHECK_DT  DATE        NOT NULL,
    DONE      ${bit} DEFAULT 0 NOT NULL,
    DONE_BY   NVARCHAR(26),
    DONE_AT   ${tstz},
    NOTE      NVARCHAR(1000),
    PRIMARY KEY (JOB_ID, CHECK_DT)
);

CREATE TABLE SM_OPS_ASSET (
    ASSET_ID        NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID      NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    TYPE            NVARCHAR(10)  NOT NULL,
    NAME            NVARCHAR(200) NOT NULL,
    HOST            NVARCHAR(300),
    OWNER           NVARCHAR(100),                    -- 담당(이름·부서 자유 입력)
    OWNER_ID        NVARCHAR(26),                     -- 알림 받을 사용자(선택)
    EXPIRES_AT      DATE,
    NOTE            NVARCHAR(2000),
    NOTIFIED_STAGE  INT DEFAULT 0 NOT NULL,      -- 만료 알림 단계 (1=30일, 2=7일, 3=1일)
    CREATED_AT      ${tstz} NOT NULL,
    UPDATED_AT      ${tstz}
);
CREATE INDEX IX_SM_OPS_ASSET_PROJECT ON SM_OPS_ASSET (PROJECT_ID, EXPIRES_AT);

CREATE TABLE SM_KB (
    KB_ID         NVARCHAR(26)  PRIMARY KEY,
