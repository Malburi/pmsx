-- 자동 생성: tools/ddl/convert_ddl.py ← common/V1__init.sql (mssql). 직접 고치지 말고 생성기를 고칠 것.
-- PMS-X R0 초기 스키마
-- 물리 PK는 대리 ID(ULID 26자), 수집 키는 (SYSTEM_ID, *_KEY) 유니크. docs/05, docs/08 §0 참고.

-- ───────── 공통 (CM) ─────────
CREATE TABLE CM_USER (
    USER_ID        NVARCHAR(26)  PRIMARY KEY,
    LOGIN_ID       NVARCHAR(50)  NOT NULL UNIQUE,
    PASSWORD_HASH  NVARCHAR(100),
    NAME           NVARCHAR(100) NOT NULL,
    ORG_TYPE       NVARCHAR(20)  DEFAULT 'INTERNAL' NOT NULL,
    AUTH_TYPE      NVARCHAR(10)  DEFAULT 'LOCAL' NOT NULL,
    ENABLED        ${bit}      DEFAULT 1 NOT NULL,
    CREATED_AT     ${tstz} NOT NULL,
    CREATED_BY     NVARCHAR(26),
    UPDATED_AT     ${tstz},
    UPDATED_BY     NVARCHAR(26)
);

CREATE TABLE CM_ROLE (
    ROLE_ID  NVARCHAR(30)  PRIMARY KEY,
    SCOPE    NVARCHAR(10)  NOT NULL,   -- SYSTEM / PROJECT
    NAME     NVARCHAR(50)  NOT NULL
);

CREATE TABLE CM_USER_ROLE (
    USER_ID  NVARCHAR(26) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID  NVARCHAR(30) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE TABLE CM_REFRESH_TOKEN (
    TOKEN_HASH  NVARCHAR(64)  PRIMARY KEY,           -- SHA-256 hex
    USER_ID     NVARCHAR(26)  NOT NULL REFERENCES CM_USER (USER_ID),
    EXPIRES_AT  ${tstz} NOT NULL,
    REVOKED     ${bit} DEFAULT 0 NOT NULL,
    CREATED_AT  ${tstz} NOT NULL
);

CREATE TABLE CM_FILE (
    FILE_ID        NVARCHAR(26)   PRIMARY KEY,
    PATH           NVARCHAR(500)  NOT NULL,
    ORIGINAL_NAME  NVARCHAR(300),
    MIME           NVARCHAR(100)  NOT NULL,
    SIZE_BYTES     BIGINT        NOT NULL,
    SHA256         NVARCHAR(64)   NOT NULL,
    CREATED_AT     ${tstz} NOT NULL,
    CREATED_BY     NVARCHAR(26)
);

-- ───────── 프로젝트 (PJ) ─────────
CREATE TABLE PJ_PROJECT (
    PROJECT_ID         NVARCHAR(26)   PRIMARY KEY,
    TYPE               NVARCHAR(2)    NOT NULL,      -- SI / SM
    NAME               NVARCHAR(200)  NOT NULL,
    CUSTOMER           NVARCHAR(200),
    START_DT           DATE,
    END_DT             DATE,
    CONTRACT_MM        DECIMAL(10, 2),
    ORIGIN_PROJECT_ID  NVARCHAR(26),
    CREATED_AT         ${tstz} NOT NULL,
    CREATED_BY         NVARCHAR(26),
    UPDATED_AT         ${tstz},
    UPDATED_BY         NVARCHAR(26)
);

CREATE TABLE PJ_MEMBER (
    PROJECT_ID  NVARCHAR(26) NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    USER_ID     NVARCHAR(26) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID     NVARCHAR(30) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    IN_DT       DATE,
    OUT_DT      DATE,
    PRIMARY KEY (PROJECT_ID, USER_ID)
);

-- ───────── As-Is 화면 분석 (AS) ─────────
CREATE TABLE AS_SYSTEM (
    SYSTEM_ID    NVARCHAR(26)  PRIMARY KEY,
    PROJECT_ID   NVARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    CODE         NVARCHAR(30)  NOT NULL,
    NAME         NVARCHAR(200) NOT NULL,
    UI_TECH      NVARCHAR(300),                      -- 콤마 구분
    SERVER_TECH  NVARCHAR(300),
    DB_TYPE      NVARCHAR(30),
    TEST_URL     NVARCHAR(500),
    CREATED_AT   ${tstz} NOT NULL,
    CREATED_BY   NVARCHAR(26),
    CONSTRAINT UQ_AS_SYSTEM UNIQUE (PROJECT_ID, CODE)
);

CREATE TABLE AS_COLLECT_RUN (
    RUN_ID             NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID          NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SEQ                INT      NOT NULL,
    RUN_KEY            NVARCHAR(100),                -- manifest.runId
    COLLECTED_AT       ${tstz} NOT NULL,
    UPLOADED_AT        ${tstz} NOT NULL,
    UPLOADED_BY        NVARCHAR(26),
    MODEL_VERSION      NVARCHAR(20),
    COLLECTOR_VERSION  NVARCHAR(50),
    PACKAGE_FILE_ID    NVARCHAR(26),
    REPORT_FILE_ID     NVARCHAR(26),
    STATS_JSON         NVARCHAR(MAX),
    DIFF_JSON          NVARCHAR(MAX),
    BLOCKED_JSON       NVARCHAR(MAX),
    FAILURES_JSON      NVARCHAR(MAX),
    CONSTRAINT UQ_AS_RUN UNIQUE (SYSTEM_ID, SEQ)
);

CREATE TABLE AS_MENU (
    MENU_ID      NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    MENU_KEY     NVARCHAR(300) NOT NULL,
    PARENT_KEY   NVARCHAR(300),
    NAME         NVARCHAR(200) NOT NULL,
    SORT_ORD     INT DEFAULT 0 NOT NULL,
    SCREEN_KEY   NVARCHAR(300),
    URL          NVARCHAR(500),
    LAST_RUN_ID  NVARCHAR(26),
    CONSTRAINT UQ_AS_MENU UNIQUE (SYSTEM_ID, MENU_KEY)
);

CREATE TABLE AS_SCREEN (
    SCREEN_ID    NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_KEY   NVARCHAR(300) NOT NULL,
    SCREEN_CODE  NVARCHAR(100) NOT NULL,
    NAME         NVARCHAR(200) NOT NULL,
    KIND         NVARCHAR(20)  DEFAULT 'page' NOT NULL,
    UI_TECH      NVARCHAR(30),
    SOURCE_FILE  NVARCHAR(500),
    URL          NVARCHAR(500),
    LAST_RUN_ID  NVARCHAR(26),
    CONSTRAINT UQ_AS_SCREEN UNIQUE (SYSTEM_ID, SCREEN_KEY)
);

CREATE TABLE AS_CAPTURE (
    CAPTURE_ID    NVARCHAR(26) PRIMARY KEY,
    SCREEN_ID     NVARCHAR(26) NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    RUN_ID        NVARCHAR(26) NOT NULL REFERENCES AS_COLLECT_RUN (RUN_ID),
    FILE_ID       NVARCHAR(26) NOT NULL REFERENCES CM_FILE (FILE_ID),
    IDX           INT     NOT NULL,
    WIDTH         INT     NOT NULL,
    HEIGHT        INT     NOT NULL,
    STATE         NVARCHAR(100),
    MASKED        ${bit} DEFAULT 0 NOT NULL,
    COLLECTED_AT  ${tstz} NOT NULL
);
CREATE INDEX IX_AS_CAPTURE_SCREEN ON AS_CAPTURE (SCREEN_ID);

CREATE TABLE AS_ELEMENT (
    ELEMENT_ID     NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID      NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_ID      NVARCHAR(26)  NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    ELEMENT_KEY    NVARCHAR(400) NOT NULL,
    SEQ_NO         INT      NOT NULL,           -- 배지 번호 (최초 등록 순서로 고정)
    ELEMENT_CODE   NVARCHAR(200) NOT NULL,
    NAME           NVARCHAR(200),
    LABEL          NVARCHAR(300),
    TYPE           NVARCHAR(20)  NOT NULL,
    BOX_X          FLOAT,
    BOX_Y          FLOAT,
    BOX_W          FLOAT,
    BOX_H          FLOAT,
    CAPTURE_INDEX  INT DEFAULT 0 NOT NULL,
    BINDING        NVARCHAR(1000),
    MATCHED        NVARCHAR(20) DEFAULT 'full' NOT NULL,
    DANGER         ${bit} DEFAULT 0 NOT NULL,
    MANUAL_YN      NCHAR(1) DEFAULT 'N' NOT NULL,
    LAST_RUN_ID    NVARCHAR(26),
    CONSTRAINT UQ_AS_ELEMENT UNIQUE (SYSTEM_ID, ELEMENT_KEY)
);
CREATE INDEX IX_AS_ELEMENT_SCREEN ON AS_ELEMENT (SCREEN_ID);

-- 함수·API·SQL·SP·테이블 노드
CREATE TABLE AS_NODE (
    NODE_ID      NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    NODE_KEY     NVARCHAR(500) NOT NULL,
    NODE_TYPE    NVARCHAR(10)  NOT NULL,              -- FN / API / SQL / SP / TABLE
    NAME         NVARCHAR(500) NOT NULL,
    LANG         NVARCHAR(20),
    FILE_PATH    NVARCHAR(500),
    LINE_START   INT,
    LINE_END     INT,
    SNIPPET      NVARCHAR(MAX),
    COMMON       ${bit} DEFAULT 0 NOT NULL,
    META_JSON    NVARCHAR(MAX),                               -- 유형별 부가 정보(method/path/serviceId, sql kind 등)
    LAST_RUN_ID  NVARCHAR(26),
    CONSTRAINT UQ_AS_NODE UNIQUE (SYSTEM_ID, NODE_KEY)
);

CREATE TABLE AS_TABLE (
    TABLE_ID      NVARCHAR(26) PRIMARY KEY REFERENCES AS_NODE (NODE_ID),
    SYSTEM_ID     NVARCHAR(26) NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCHEMA_NM     NVARCHAR(100),
    TABLE_NM      NVARCHAR(200) NOT NULL,
    COMMENT_TXT   NVARCHAR(1000),
    KIND          NVARCHAR(20) DEFAULT 'table' NOT NULL,
    ROW_COUNT     BIGINT,
    SUBJECT_AREA  NVARCHAR(100),
    INDEXES_JSON  NVARCHAR(MAX)
);

CREATE TABLE AS_COLUMN (
    TABLE_ID     NVARCHAR(26)  NOT NULL REFERENCES AS_TABLE (TABLE_ID),
    COLUMN_NM    NVARCHAR(200) NOT NULL,
    ORD          INT      NOT NULL,
    DATA_TYPE    NVARCHAR(100) NOT NULL,
    NULLABLE     ${bit},
    PK           ${bit} DEFAULT 0 NOT NULL,
    DEFAULT_VAL  NVARCHAR(500),
    COMMENT_TXT  NVARCHAR(1000),
    PRIMARY KEY (TABLE_ID, COLUMN_NM)
);

CREATE TABLE AS_RELATION (
    REL_ID        NVARCHAR(26)   PRIMARY KEY,
    SYSTEM_ID     NVARCHAR(26)   NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    CHILD_KEY     NVARCHAR(500)  NOT NULL,
    PARENT_KEY    NVARCHAR(500)  NOT NULL,
    COLUMN_PAIRS  NVARCHAR(1000) NOT NULL,            -- JSON [["A","B"],...]
    KIND          NVARCHAR(10)   NOT NULL,            -- fk / inferred
    EVIDENCE_CNT  INT,
    CONFIDENCE    FLOAT,
    DECISION      NVARCHAR(10) DEFAULT 'pending' NOT NULL,
    LAST_RUN_ID   NVARCHAR(26),
    CONSTRAINT UQ_AS_RELATION UNIQUE (SYSTEM_ID, CHILD_KEY, PARENT_KEY, COLUMN_PAIRS)
);

-- 모든 연결선 (요소→함수→API→서버→SQL→테이블, 화면 이동 등). FROM/TO 는 수집 키.
CREATE TABLE AS_EDGE (
    EDGE_ID      NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    FROM_KEY     NVARCHAR(500) NOT NULL,
    TO_KEY       NVARCHAR(500) NOT NULL,
    KIND         NVARCHAR(20)  NOT NULL,
    EVENT        NVARCHAR(100) DEFAULT '' NOT NULL,
    ORD          INT,
    MODEL_SEQ    INT,                            -- 수집 모델 내 순서 (ORD 없을 때 정렬 기준)
    COND         NVARCHAR(500),
    CRUD         NVARCHAR(4),
    COLUMNS_TXT  NVARCHAR(2000),
    SOURCE       NVARCHAR(10)  NOT NULL,              -- static / dynamic / manual
    CONFIDENCE   FLOAT NOT NULL,
    EVIDENCE     NVARCHAR(1000),
    STATUS       NVARCHAR(10) DEFAULT 'active' NOT NULL,
    LAST_RUN_ID  NVARCHAR(26),
    CONSTRAINT UQ_AS_EDGE UNIQUE (SYSTEM_ID, FROM_KEY, TO_KEY, KIND, EVENT)
);
CREATE INDEX IX_AS_EDGE_FROM ON AS_EDGE (SYSTEM_ID, FROM_KEY);
CREATE INDEX IX_AS_EDGE_TO ON AS_EDGE (SYSTEM_ID, TO_KEY);

CREATE TABLE AS_ANALYSIS (
    SCREEN_ID     NVARCHAR(26) PRIMARY KEY REFERENCES AS_SCREEN (SCREEN_ID),
    STATUS        NVARCHAR(10) DEFAULT 'AUTO' NOT NULL,   -- AUTO / WORKING / REVIEW / DONE
    OWNER_ID      NVARCHAR(26),
    REVIEWER_ID   NVARCHAR(26),
    CONFIRMED_AT  ${tstz},
    UPDATED_AT    ${tstz} NOT NULL,
    UPDATED_BY    NVARCHAR(26)
);

CREATE TABLE AS_NOTE (
    NOTE_ID     NVARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID   NVARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    TARGET_KEY  NVARCHAR(500) NOT NULL,
    CONTENT     NVARCHAR(MAX)         NOT NULL,
    AUTHOR_ID   NVARCHAR(26)  NOT NULL,
    CREATED_AT  ${tstz} NOT NULL
);

