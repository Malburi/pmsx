-- H2(MODE=PostgreSQL) / PostgreSQL 공용 문법

-- 요소: 숨김(수집 요소 삭제 대신), 수정 이력
ALTER TABLE AS_ELEMENT ADD COLUMN HIDDEN BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE AS_ELEMENT ADD COLUMN ORIGIN VARCHAR(10) DEFAULT 'collect' NOT NULL;   -- collect / manual(편집기에서 추가)
ALTER TABLE AS_ELEMENT ADD COLUMN UPDATED_AT TIMESTAMP WITH TIME ZONE;
ALTER TABLE AS_ELEMENT ADD COLUMN UPDATED_BY VARCHAR(26);

-- 노드: 수동 생성 노드
ALTER TABLE AS_NODE ADD COLUMN MANUAL_YN CHAR(1) DEFAULT 'N' NOT NULL;

-- 엣지: 확정(confirmed) / 수집 엣지 수정됨(edited → 재수집 시 보존)
ALTER TABLE AS_EDGE ADD COLUMN CONFIRMED BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE AS_EDGE ADD COLUMN EDITED BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE AS_EDGE ADD COLUMN UPDATED_AT TIMESTAMP WITH TIME ZONE;
ALTER TABLE AS_EDGE ADD COLUMN UPDATED_BY VARCHAR(26);

-- 캡처: 수동 업로드 (수집 회차 없음)
ALTER TABLE AS_CAPTURE ALTER COLUMN RUN_ID DROP NOT NULL;
ALTER TABLE AS_CAPTURE ADD COLUMN MANUAL BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE AS_CAPTURE ADD COLUMN UPLOADED_BY VARCHAR(26);
CREATE INDEX IX_AS_CAPTURE_SCREEN_AT ON AS_CAPTURE (SCREEN_ID, COLLECTED_AT);

-- 메모: 대상 유형·대리 ID
ALTER TABLE AS_NOTE ADD COLUMN TARGET_TYPE VARCHAR(10);
ALTER TABLE AS_NOTE ADD COLUMN TARGET_ID VARCHAR(26);
ALTER TABLE AS_NOTE ADD COLUMN UPDATED_AT TIMESTAMP WITH TIME ZONE;
CREATE INDEX IX_AS_NOTE_TARGET ON AS_NOTE (TARGET_TYPE, TARGET_ID);

-- 분석 상태 이력
CREATE TABLE AS_ANALYSIS_HIST (
    HIST_ID      VARCHAR(26) PRIMARY KEY,
    SCREEN_ID    VARCHAR(26) NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    CHANGED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    USER_ID      VARCHAR(26),
    FROM_STATUS  VARCHAR(10),
    TO_STATUS    VARCHAR(10) NOT NULL,
    OWNER_ID     VARCHAR(26),
    REVIEWER_ID  VARCHAR(26),
    COMMENT_TXT  VARCHAR(1000)
);
CREATE INDEX IX_AS_ANALYSIS_HIST ON AS_ANALYSIS_HIST (SCREEN_ID, CHANGED_AT);

-- 테이블: 수동 코멘트 (수집 코멘트보다 우선, 재수집 시 보존). SUBJECT_AREA 도 재수집 시 보존.
ALTER TABLE AS_TABLE ADD COLUMN COMMENT_MANUAL VARCHAR(1000);

-- 관계: 수동 추가 작성자
ALTER TABLE AS_RELATION ADD COLUMN CREATED_BY VARCHAR(26);
ALTER TABLE AS_RELATION ADD COLUMN UPDATED_AT TIMESTAMP WITH TIME ZONE;
ALTER TABLE AS_RELATION ADD COLUMN UPDATED_BY VARCHAR(26);

-- 회차 diff 상세 (추가·삭제 키 목록)
ALTER TABLE AS_COLLECT_RUN ADD COLUMN DIFF_DETAIL_JSON TEXT;

-- 조회 성능 (화면/요소/메뉴의 최신 회차 필터, 노드 유형 검색, 역방향 탐색)
CREATE INDEX IX_AS_SCREEN_RUN ON AS_SCREEN (SYSTEM_ID, LAST_RUN_ID);
CREATE INDEX IX_AS_MENU_RUN ON AS_MENU (SYSTEM_ID, LAST_RUN_ID);
CREATE INDEX IX_AS_NODE_TYPE ON AS_NODE (SYSTEM_ID, NODE_TYPE);
CREATE INDEX IX_AS_EDGE_KIND ON AS_EDGE (SYSTEM_ID, KIND);
CREATE INDEX IX_AS_RELATION_CHILD ON AS_RELATION (SYSTEM_ID, CHILD_KEY);
CREATE INDEX IX_AS_RELATION_PARENT ON AS_RELATION (SYSTEM_ID, PARENT_KEY);
CREATE INDEX IX_AS_TABLE_SYSTEM ON AS_TABLE (SYSTEM_ID, SUBJECT_AREA);
