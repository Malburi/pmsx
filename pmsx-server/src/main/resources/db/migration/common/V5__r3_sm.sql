-- PMS-X R3: SM 운영 (SR·SLA·장애·문제·변경·정기 작업·운영 자산·KB·월간 운영보고) (docs/13 명세)
-- H2(MODE=PostgreSQL) / PostgreSQL 공용 문법만 사용

-- ───────── SLA 정책 ─────────
CREATE TABLE SM_SLA_POLICY (
    POLICY_ID          VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID         VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME               VARCHAR(200) NOT NULL,
    TYPES              VARCHAR(200),                 -- 콤마 구분, 비면 전체
    PRIORITIES         VARCHAR(50),                  -- 콤마 구분, 비면 전체
    RESPONSE_MIN       INTEGER      NOT NULL,
    RESOLVE_MIN        INTEGER      NOT NULL,
    BH_START           VARCHAR(5)   DEFAULT '09:00' NOT NULL,
    BH_END             VARCHAR(5)   DEFAULT '18:00' NOT NULL,
    BH_DAYS            VARCHAR(20)  DEFAULT '1,2,3,4,5' NOT NULL,   -- ISO 요일 1=월 … 7=일
    TWENTY_FOUR_SEVEN  BOOLEAN DEFAULT FALSE NOT NULL,
    ORD                INTEGER DEFAULT 0 NOT NULL,
    CREATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT         TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IX_SM_SLA_POLICY_PROJECT ON SM_SLA_POLICY (PROJECT_ID, ORD);

-- ───────── SR ─────────
CREATE TABLE SM_SR (
    SR_ID          VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID     VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    SR_NO          VARCHAR(30)  NOT NULL,
    TYPE           VARCHAR(10)  NOT NULL,
    PRIORITY       VARCHAR(2)   NOT NULL,
    TITLE          VARCHAR(300) NOT NULL,
    DESCRIPTION    TEXT,
    CHANNEL        VARCHAR(10)  NOT NULL,
    REQ_NAME       VARCHAR(100) NOT NULL,
    REQ_ORG        VARCHAR(200),
    REQ_CONTACT    VARCHAR(200),
    REQ_USER_ID    VARCHAR(26),
    STATUS         VARCHAR(12)  DEFAULT 'RECEIVED' NOT NULL,
    ASSIGNEE_ID    VARCHAR(26),
    SYSTEM_ID      VARCHAR(26),
    SCREEN_ID      VARCHAR(26),
    ELEMENT_ID     VARCHAR(26),
    POLICY_ID      VARCHAR(26),
    RESPONDED_AT   TIMESTAMP WITH TIME ZONE,
    RESOLVED_AT    TIMESTAMP WITH TIME ZONE,
    CLOSED_AT      TIMESTAMP WITH TIME ZONE,
    REJECT_REASON  VARCHAR(1000),
    NOTIFY_FLAGS   VARCHAR(100),                     -- SLA 알림 1회 발송 기록 (RESP_SOON,RESP_BREACH,RES_SOON,RES_BREACH)
    MESSAGE_ID     VARCHAR(300),                     -- 메일 접수 중복 방지
    ORIGIN_DEFECT_ID VARCHAR(26),                    -- SI→SM 인수인계로 생성된 경우 원래 결함
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR(26),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY     VARCHAR(26),
    CONSTRAINT UQ_SM_SR_NO UNIQUE (PROJECT_ID, SR_NO)
);
CREATE INDEX IX_SM_SR_PROJECT ON SM_SR (PROJECT_ID, STATUS);
CREATE INDEX IX_SM_SR_SCREEN ON SM_SR (SCREEN_ID);
CREATE INDEX IX_SM_SR_CREATED ON SM_SR (PROJECT_ID, CREATED_AT);
CREATE INDEX IX_SM_SR_MESSAGE ON SM_SR (MESSAGE_ID);

-- SLA 시계 이벤트 (START / PAUSE / RESUME / STOP)
CREATE TABLE SM_SLA_EVENT (
    SR_ID     VARCHAR(26) NOT NULL,
    SEQ       INTEGER     NOT NULL,
    EVENT     VARCHAR(10) NOT NULL,
    EVENT_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (SR_ID, SEQ)
);

CREATE TABLE SM_SR_COMMENT (
    COMMENT_ID  VARCHAR(26) PRIMARY KEY,
    SR_ID       VARCHAR(26) NOT NULL,
    CONTENT     TEXT        NOT NULL,
    INTERNAL    BOOLEAN DEFAULT FALSE NOT NULL,
    AUTHOR_ID   VARCHAR(26) NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IX_SM_SR_COMMENT ON SM_SR_COMMENT (SR_ID, CREATED_AT);

-- ───────── 장애·문제·변경 ─────────
CREATE TABLE SM_INCIDENT (
    INCIDENT_ID   VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID    VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    INCIDENT_NO   VARCHAR(30)  NOT NULL,
    TITLE         VARCHAR(300) NOT NULL,
    GRADE         INTEGER      NOT NULL,
    STATUS        VARCHAR(10)  DEFAULT 'OPEN' NOT NULL,
    STARTED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    DETECTED_AT   TIMESTAMP WITH TIME ZONE,
    RECOVERED_AT  TIMESTAMP WITH TIME ZONE,
    IMPACT        TEXT,
    SYSTEM_IDS    TEXT,
    CAUSE         TEXT,
    RCA           TEXT,
    PREVENTION    TEXT,
    SR_IDS        TEXT,
    CREATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY    VARCHAR(26),
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY    VARCHAR(26)
);
CREATE INDEX IX_SM_INCIDENT_PROJECT ON SM_INCIDENT (PROJECT_ID, STARTED_AT);

CREATE TABLE SM_INCIDENT_TIMELINE (
    ITEM_ID      VARCHAR(26) PRIMARY KEY,
    INCIDENT_ID  VARCHAR(26) NOT NULL,
    EVENT_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONTENT      VARCHAR(2000) NOT NULL,
    CREATED_BY   VARCHAR(26)
);
CREATE INDEX IX_SM_INCIDENT_TL ON SM_INCIDENT_TIMELINE (INCIDENT_ID, EVENT_AT);

CREATE TABLE SM_PROBLEM (
    PROBLEM_ID    VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID    VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    PROBLEM_NO    VARCHAR(30)  NOT NULL,
    TITLE         VARCHAR(300) NOT NULL,
    ROOT_CAUSE    TEXT,
    WORKAROUND    TEXT,
    KNOWN_ERROR   BOOLEAN DEFAULT FALSE NOT NULL,
    STATUS        VARCHAR(10)  DEFAULT 'OPEN' NOT NULL,
    SR_IDS        TEXT,
    INCIDENT_IDS  TEXT,
    CREATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY    VARCHAR(26),
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY    VARCHAR(26)
);
CREATE INDEX IX_SM_PROBLEM_PROJECT ON SM_PROBLEM (PROJECT_ID);

CREATE TABLE SM_CHANGE (
    CHANGE_ID      VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID     VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    CHANGE_NO      VARCHAR(30)  NOT NULL,
    TITLE          VARCHAR(300) NOT NULL,
    TYPE           VARCHAR(10)  NOT NULL,
    RISK           VARCHAR(1)   DEFAULT 'M' NOT NULL,
    PLAN_TXT       TEXT,
    ROLLBACK_PLAN  TEXT,
    SCHEDULED_AT   TIMESTAMP WITH TIME ZONE,
    DEPLOYED_AT    TIMESTAMP WITH TIME ZONE,
    STATUS         VARCHAR(12)  DEFAULT 'REQUESTED' NOT NULL,
    SR_IDS         TEXT,
    SCREEN_IDS     TEXT,
    COMMITS        TEXT,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR(26),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY     VARCHAR(26)
);
CREATE INDEX IX_SM_CHANGE_PROJECT ON SM_CHANGE (PROJECT_ID, SCHEDULED_AT);

CREATE TABLE SM_CHANGE_CAB (
    CHANGE_ID    VARCHAR(26) NOT NULL,
    USER_ID      VARCHAR(26) NOT NULL,
    DECISION     VARCHAR(10) NOT NULL,
    COMMENT_TXT  VARCHAR(1000),
    DECIDED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (CHANGE_ID, USER_ID)
);

-- ───────── 정기 작업·운영 자산·KB ─────────
CREATE TABLE SM_ROUTINE_JOB (
    JOB_ID          VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID      VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME            VARCHAR(200) NOT NULL,
    FREQ            VARCHAR(10)  NOT NULL,           -- DAILY / WEEKLY / MONTHLY
    DOW             VARCHAR(20),                     -- WEEKLY: ISO 요일 콤마 구분
    DAY_OF_MONTH    INTEGER,                         -- MONTHLY: 1~31 (말일 초과 시 말일)
    OWNER_ID        VARCHAR(26),
    CHECKLIST_JSON  TEXT,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE SM_ROUTINE_CHECK (
    JOB_ID    VARCHAR(26) NOT NULL,
    CHECK_DT  DATE        NOT NULL,
    DONE      BOOLEAN DEFAULT FALSE NOT NULL,
    DONE_BY   VARCHAR(26),
    DONE_AT   TIMESTAMP WITH TIME ZONE,
    NOTE      VARCHAR(1000),
    PRIMARY KEY (JOB_ID, CHECK_DT)
);

CREATE TABLE SM_OPS_ASSET (
    ASSET_ID        VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID      VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    TYPE            VARCHAR(10)  NOT NULL,
    NAME            VARCHAR(200) NOT NULL,
    HOST            VARCHAR(300),
    OWNER           VARCHAR(100),                    -- 담당(이름·부서 자유 입력)
    OWNER_ID        VARCHAR(26),                     -- 알림 받을 사용자(선택)
    EXPIRES_AT      DATE,
    NOTE            VARCHAR(2000),
    NOTIFIED_STAGE  INTEGER DEFAULT 0 NOT NULL,      -- 만료 알림 단계 (1=30일, 2=7일, 3=1일)
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IX_SM_OPS_ASSET_PROJECT ON SM_OPS_ASSET (PROJECT_ID, EXPIRES_AT);

CREATE TABLE SM_KB (
    KB_ID         VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID    VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    KB_NO         VARCHAR(30)  NOT NULL,
    TITLE         VARCHAR(300) NOT NULL,
    CONTENT       TEXT         NOT NULL,
    TAGS          VARCHAR(500),
    SYSTEM_ID     VARCHAR(26),
    SCREEN_ID     VARCHAR(26),
    SOURCE_SR_ID  VARCHAR(26),
    CREATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY    VARCHAR(26),
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY    VARCHAR(26)
);
CREATE INDEX IX_SM_KB_PROJECT ON SM_KB (PROJECT_ID);

-- ───────── 월간 운영보고 ─────────
CREATE TABLE SM_MONTHLY_REPORT (
    REPORT_ID   VARCHAR(26) PRIMARY KEY,
    PROJECT_ID  VARCHAR(26) NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    YM          VARCHAR(7)  NOT NULL,
    SUMMARY     TEXT,
    PLAN_TXT    TEXT,
    DATA_JSON   TEXT        NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY  VARCHAR(26),
    UPDATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY  VARCHAR(26),
    CONSTRAINT UQ_SM_MONTHLY UNIQUE (PROJECT_ID, YM)
