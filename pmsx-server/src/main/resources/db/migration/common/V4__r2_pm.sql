-- ───────── WBS ─────────
CREATE TABLE PJ_WBS (
    WBS_ID          VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID      VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    PARENT_ID       VARCHAR(26),
    WBS_NO          VARCHAR(50)  NOT NULL,
    NAME            VARCHAR(300) NOT NULL,
    ORD             INTEGER      NOT NULL,
    PLAN_START      DATE,
    PLAN_END        DATE,
    ACT_START       DATE,
    ACT_END         DATE,
    WEIGHT          NUMERIC(10, 2) DEFAULT 1 NOT NULL,
    PROGRESS        NUMERIC(5, 1)  DEFAULT 0 NOT NULL,
    MILESTONE       BOOLEAN DEFAULT FALSE NOT NULL,
    STATUS          VARCHAR(12)  DEFAULT 'TODO' NOT NULL,
    DELIVERABLE_ID  VARCHAR(26),
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE,
    UPDATED_BY      VARCHAR(26)
);
CREATE INDEX IX_PJ_WBS_PROJECT ON PJ_WBS (PROJECT_ID, ORD);

CREATE TABLE PJ_WBS_DEP (
    PRED_ID   VARCHAR(26) NOT NULL,
    SUCC_ID   VARCHAR(26) NOT NULL,
    DEP_TYPE  VARCHAR(2)  DEFAULT 'FS' NOT NULL,
    LAG_DAYS  INTEGER     DEFAULT 0 NOT NULL,
    PRIMARY KEY (PRED_ID, SUCC_ID)
);
CREATE INDEX IX_PJ_WBS_DEP_SUCC ON PJ_WBS_DEP (SUCC_ID);

CREATE TABLE PJ_BASELINE (
    BASELINE_ID  VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID   VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME         VARCHAR(200) NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
