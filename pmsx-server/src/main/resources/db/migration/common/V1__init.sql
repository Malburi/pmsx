-- PMS-X R0 초기 스키마 (H2 MODE=PostgreSQL / PostgreSQL 공용)
-- 물리 PK는 대리 ID(ULID 26자), 수집 키는 (SYSTEM_ID, *_KEY) 유니크. docs/05, docs/08 §0 참고.

-- ───────── 공통 (CM) ─────────
CREATE TABLE CM_USER (
    USER_ID        VARCHAR(26)  PRIMARY KEY,
    LOGIN_ID       VARCHAR(50)  NOT NULL UNIQUE,
    PASSWORD_HASH  VARCHAR(100),
    NAME           VARCHAR(100) NOT NULL,
    ORG_TYPE       VARCHAR(20)  DEFAULT 'INTERNAL' NOT NULL,
    AUTH_TYPE      VARCHAR(10)  DEFAULT 'LOCAL' NOT NULL,
    ENABLED        BOOLEAN      DEFAULT TRUE NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR(26),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE,
    UPDATED_BY     VARCHAR(26)
);

CREATE TABLE CM_ROLE (
    ROLE_ID  VARCHAR(30)  PRIMARY KEY,
    SCOPE    VARCHAR(10)  NOT NULL,   -- SYSTEM / PROJECT
    NAME     VARCHAR(50)  NOT NULL
);

CREATE TABLE CM_USER_ROLE (
    USER_ID  VARCHAR(26) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID  VARCHAR(30) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE TABLE CM_REFRESH_TOKEN (
    TOKEN_HASH  VARCHAR(64)  PRIMARY KEY,           -- SHA-256 hex
    USER_ID     VARCHAR(26)  NOT NULL REFERENCES CM_USER (USER_ID),
    EXPIRES_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED     BOOLEAN DEFAULT FALSE NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE CM_FILE (
    FILE_ID        VARCHAR(26)   PRIMARY KEY,
    PATH           VARCHAR(500)  NOT NULL,
    ORIGINAL_NAME  VARCHAR(300),
    MIME           VARCHAR(100)  NOT NULL,
    SIZE_BYTES     BIGINT        NOT NULL,
    SHA256         VARCHAR(64)   NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR(26)
);

-- ───────── 프로젝트 (PJ) ─────────
CREATE TABLE PJ_PROJECT (
    PROJECT_ID         VARCHAR(26)   PRIMARY KEY,
    TYPE               VARCHAR(2)    NOT NULL,      -- SI / SM
    NAME               VARCHAR(200)  NOT NULL,
    CUSTOMER           VARCHAR(200),
    START_DT           DATE,
    END_DT             DATE,
    CONTRACT_MM        NUMERIC(10, 2),
    ORIGIN_PROJECT_ID  VARCHAR(26),
    CREATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY         VARCHAR(26),
    UPDATED_AT         TIMESTAMP WITH TIME ZONE,
    UPDATED_BY         VARCHAR(26)
);

CREATE TABLE PJ_MEMBER (
    PROJECT_ID  VARCHAR(26) NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    USER_ID     VARCHAR(26) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID     VARCHAR(30) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    IN_DT       DATE,
    OUT_DT      DATE,
    PRIMARY KEY (PROJECT_ID, USER_ID)
);

-- ───────── As-Is 화면 분석 (AS) ─────────
CREATE TABLE AS_SYSTEM (
    SYSTEM_ID    VARCHAR(26)  PRIMARY KEY,
    PROJECT_ID   VARCHAR(26)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    CODE         VARCHAR(30)  NOT NULL,
    NAME         VARCHAR(200) NOT NULL,
    UI_TECH      VARCHAR(300),                      -- 콤마 구분
    SERVER_TECH  VARCHAR(300),
    DB_TYPE      VARCHAR(30),
    TEST_URL     VARCHAR(500),
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY   VARCHAR(26),
    CONSTRAINT UQ_AS_SYSTEM UNIQUE (PROJECT_ID, CODE)
);

CREATE TABLE AS_COLLECT_RUN (
    RUN_ID             VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID          VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SEQ                INTEGER      NOT NULL,
    RUN_KEY            VARCHAR(100),                -- manifest.runId
    COLLECTED_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
    UPLOADED_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    UPLOADED_BY        VARCHAR(26),
    MODEL_VERSION      VARCHAR(20),
    COLLECTOR_VERSION  VARCHAR(50),
    PACKAGE_FILE_ID    VARCHAR(26),
    REPORT_FILE_ID     VARCHAR(26),
    STATS_JSON         TEXT,
    DIFF_JSON          TEXT,
    BLOCKED_JSON       TEXT,
    FAILURES_JSON      TEXT,
    CONSTRAINT UQ_AS_RUN UNIQUE (SYSTEM_ID, SEQ)
);

CREATE TABLE AS_MENU (
    MENU_ID      VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    MENU_KEY     VARCHAR(300) NOT NULL,
    PARENT_KEY   VARCHAR(300),
    NAME         VARCHAR(200) NOT NULL,
    SORT_ORD     INTEGER DEFAULT 0 NOT NULL,
    SCREEN_KEY   VARCHAR(300),
    URL          VARCHAR(500),
    LAST_RUN_ID  VARCHAR(26),
    CONSTRAINT UQ_AS_MENU UNIQUE (SYSTEM_ID, MENU_KEY)
);

CREATE TABLE AS_SCREEN (
    SCREEN_ID    VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_KEY   VARCHAR(300) NOT NULL,
    SCREEN_CODE  VARCHAR(100) NOT NULL,
    NAME         VARCHAR(200) NOT NULL,
    KIND         VARCHAR(20)  DEFAULT 'page' NOT NULL,
    UI_TECH      VARCHAR(30),
    SOURCE_FILE  VARCHAR(500),
    URL          VARCHAR(500),
    LAST_RUN_ID  VARCHAR(26),
    CONSTRAINT UQ_AS_SCREEN UNIQUE (SYSTEM_ID, SCREEN_KEY)
);

CREATE TABLE AS_CAPTURE (
    CAPTURE_ID    VARCHAR(26) PRIMARY KEY,
    SCREEN_ID     VARCHAR(26) NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    RUN_ID        VARCHAR(26) NOT NULL REFERENCES AS_COLLECT_RUN (RUN_ID),
    FILE_ID       VARCHAR(26) NOT NULL REFERENCES CM_FILE (FILE_ID),
    IDX           INTEGER     NOT NULL,
    WIDTH         INTEGER     NOT NULL,
    HEIGHT        INTEGER     NOT NULL,
    STATE         VARCHAR(100),
    MASKED        BOOLEAN DEFAULT FALSE NOT NULL,
    COLLECTED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IX_AS_CAPTURE_SCREEN ON AS_CAPTURE (SCREEN_ID);

CREATE TABLE AS_ELEMENT (
    ELEMENT_ID     VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID      VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_ID      VARCHAR(26)  NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    ELEMENT_KEY    VARCHAR(400) NOT NULL,
    SEQ_NO         INTEGER      NOT NULL,           -- 배지 번호 (최초 등록 순서로 고정)
    ELEMENT_CODE   VARCHAR(200) NOT NULL,
    NAME           VARCHAR(200),
    LABEL          VARCHAR(300),
    TYPE           VARCHAR(20)  NOT NULL,
    BOX_X          DOUBLE PRECISION,
    BOX_Y          DOUBLE PRECISION,
    BOX_W          DOUBLE PRECISION,
    BOX_H          DOUBLE PRECISION,
    CAPTURE_INDEX  INTEGER DEFAULT 0 NOT NULL,
    BINDING        VARCHAR(1000),
    MATCHED        VARCHAR(20) DEFAULT 'full' NOT NULL,
    DANGER         BOOLEAN DEFAULT FALSE NOT NULL,
    MANUAL_YN      CHAR(1) DEFAULT 'N' NOT NULL,
    LAST_RUN_ID    VARCHAR(26),
    CONSTRAINT UQ_AS_ELEMENT UNIQUE (SYSTEM_ID, ELEMENT_KEY)
);
CREATE INDEX IX_AS_ELEMENT_SCREEN ON AS_ELEMENT (SCREEN_ID);

-- 함수·API·SQL·SP·테이블 노드
CREATE TABLE AS_NODE (
    NODE_ID      VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    NODE_KEY     VARCHAR(500) NOT NULL,
    NODE_TYPE    VARCHAR(10)  NOT NULL,              -- FN / API / SQL / SP / TABLE
    NAME         VARCHAR(500) NOT NULL,
    LANG         VARCHAR(20),
    FILE_PATH    VARCHAR(500),
    LINE_START   INTEGER,
    LINE_END     INTEGER,
    SNIPPET      TEXT,
    COMMON       BOOLEAN DEFAULT FALSE NOT NULL,
    META_JSON    TEXT,                               -- 유형별 부가 정보(method/path/serviceId, sql kind 등)
    LAST_RUN_ID  VARCHAR(26),
    CONSTRAINT UQ_AS_NODE UNIQUE (SYSTEM_ID, NODE_KEY)
);

CREATE TABLE AS_TABLE (
    TABLE_ID      VARCHAR(26) PRIMARY KEY REFERENCES AS_NODE (NODE_ID),
    SYSTEM_ID     VARCHAR(26) NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCHEMA_NM     VARCHAR(100),
    TABLE_NM      VARCHAR(200) NOT NULL,
    COMMENT_TXT   VARCHAR(1000),
    KIND          VARCHAR(20) DEFAULT 'table' NOT NULL,
    ROW_COUNT     BIGINT,
    SUBJECT_AREA  VARCHAR(100),
    INDEXES_JSON  TEXT
);

CREATE TABLE AS_COLUMN (
    TABLE_ID     VARCHAR(26)  NOT NULL REFERENCES AS_TABLE (TABLE_ID),
    COLUMN_NM    VARCHAR(200) NOT NULL,
    ORD          INTEGER      NOT NULL,
    DATA_TYPE    VARCHAR(100) NOT NULL,
    NULLABLE     BOOLEAN,
    PK           BOOLEAN DEFAULT FALSE NOT NULL,
    DEFAULT_VAL  VARCHAR(500),
    COMMENT_TXT  VARCHAR(1000),
    PRIMARY KEY (TABLE_ID, COLUMN_NM)
);

CREATE TABLE AS_RELATION (
    REL_ID        VARCHAR(26)   PRIMARY KEY,
    SYSTEM_ID     VARCHAR(26)   NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    CHILD_KEY     VARCHAR(500)  NOT NULL,
    PARENT_KEY    VARCHAR(500)  NOT NULL,
    COLUMN_PAIRS  VARCHAR(1000) NOT NULL,            -- JSON [["A","B"],...]
    KIND          VARCHAR(10)   NOT NULL,            -- fk / inferred
    EVIDENCE_CNT  INTEGER,
    CONFIDENCE    DOUBLE PRECISION,
    DECISION      VARCHAR(10) DEFAULT 'pending' NOT NULL,
    LAST_RUN_ID   VARCHAR(26),
    CONSTRAINT UQ_AS_RELATION UNIQUE (SYSTEM_ID, CHILD_KEY, PARENT_KEY, COLUMN_PAIRS)
);

-- 모든 연결선 (요소→함수→API→서버→SQL→테이블, 화면 이동 등). FROM/TO 는 수집 키.
CREATE TABLE AS_EDGE (
    EDGE_ID      VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    FROM_KEY     VARCHAR(500) NOT NULL,
    TO_KEY       VARCHAR(500) NOT NULL,
    KIND         VARCHAR(20)  NOT NULL,
    EVENT        VARCHAR(100) DEFAULT '' NOT NULL,
    ORD          INTEGER,
    MODEL_SEQ    INTEGER,                            -- 수집 모델 내 순서 (ORD 없을 때 정렬 기준)
    COND         VARCHAR(500),
    CRUD         VARCHAR(4),
    COLUMNS_TXT  VARCHAR(2000),
    SOURCE       VARCHAR(10)  NOT NULL,              -- static / dynamic / manual
    CONFIDENCE   DOUBLE PRECISION NOT NULL,
    EVIDENCE     VARCHAR(1000),
    STATUS       VARCHAR(10) DEFAULT 'active' NOT NULL,
    LAST_RUN_ID  VARCHAR(26),
    CONSTRAINT UQ_AS_EDGE UNIQUE (SYSTEM_ID, FROM_KEY, TO_KEY, KIND, EVENT)
);
CREATE INDEX IX_AS_EDGE_FROM ON AS_EDGE (SYSTEM_ID, FROM_KEY);
CREATE INDEX IX_AS_EDGE_TO ON AS_EDGE (SYSTEM_ID, TO_KEY);

CREATE TABLE AS_ANALYSIS (
    SCREEN_ID     VARCHAR(26) PRIMARY KEY REFERENCES AS_SCREEN (SCREEN_ID),
    STATUS        VARCHAR(10) DEFAULT 'AUTO' NOT NULL,   -- AUTO / WORKING / REVIEW / DONE
    OWNER_ID      VARCHAR(26),
    REVIEWER_ID   VARCHAR(26),
    CONFIRMED_AT  TIMESTAMP WITH TIME ZONE,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY    VARCHAR(26)
);

CREATE TABLE AS_NOTE (
    NOTE_ID     VARCHAR(26)  PRIMARY KEY,
    SYSTEM_ID   VARCHAR(26)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    TARGET_KEY  VARCHAR(500) NOT NULL,
    CONTENT     TEXT         NOT NULL,
    AUTHOR_ID   VARCHAR(26)  NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);

