-- 자동 생성: tools/ddl/convert_ddl.py ← common/V1__init.sql (oracle). 직접 고치지 말고 생성기를 고칠 것.
-- PMS-X R0 초기 스키마
-- 물리 PK는 대리 ID(ULID 26자), 수집 키는 (SYSTEM_ID, *_KEY) 유니크. docs/05, docs/08 §0 참고.

-- ───────── 공통 (CM) ─────────
CREATE TABLE CM_USER (
    USER_ID        VARCHAR2(26 CHAR)  PRIMARY KEY,
    LOGIN_ID       VARCHAR2(50 CHAR)  NOT NULL UNIQUE,
    PASSWORD_HASH  VARCHAR2(100 CHAR),
    NAME           VARCHAR2(100 CHAR) NOT NULL,
    ORG_TYPE       VARCHAR2(20 CHAR)  DEFAULT 'INTERNAL' NOT NULL,
    AUTH_TYPE      VARCHAR2(10 CHAR)  DEFAULT 'LOCAL' NOT NULL,
    ENABLED        NUMBER(1)      DEFAULT 1 NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR2(26 CHAR),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE,
    UPDATED_BY     VARCHAR2(26 CHAR)
);

CREATE TABLE CM_ROLE (
    ROLE_ID  VARCHAR2(30 CHAR)  PRIMARY KEY,
    SCOPE    VARCHAR2(10 CHAR)  NOT NULL,   -- SYSTEM / PROJECT
    NAME     VARCHAR2(50 CHAR)  NOT NULL
);

CREATE TABLE CM_USER_ROLE (
    USER_ID  VARCHAR2(26 CHAR) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID  VARCHAR2(30 CHAR) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE TABLE CM_REFRESH_TOKEN (
    TOKEN_HASH  VARCHAR2(64 CHAR)  PRIMARY KEY,           -- SHA-256 hex
    USER_ID     VARCHAR2(26 CHAR)  NOT NULL REFERENCES CM_USER (USER_ID),
    EXPIRES_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    REVOKED     NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE CM_FILE (
    FILE_ID        VARCHAR2(26 CHAR)   PRIMARY KEY,
    PATH           VARCHAR2(500 CHAR)  NOT NULL,
    ORIGINAL_NAME  VARCHAR2(300 CHAR),
    MIME           VARCHAR2(100 CHAR)  NOT NULL,
    SIZE_BYTES     NUMBER(19)        NOT NULL,
    SHA256         VARCHAR2(64 CHAR)   NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR2(26 CHAR)
);

-- ───────── 프로젝트 (PJ) ─────────
CREATE TABLE PJ_PROJECT (
    PROJECT_ID         VARCHAR2(26 CHAR)   PRIMARY KEY,
    TYPE               VARCHAR2(2 CHAR)    NOT NULL,      -- SI / SM
    NAME               VARCHAR2(200 CHAR)  NOT NULL,
    CUSTOMER           VARCHAR2(200 CHAR),
    START_DT           DATE,
    END_DT             DATE,
    CONTRACT_MM        NUMBER(10, 2),
    ORIGIN_PROJECT_ID  VARCHAR2(26 CHAR),
    CREATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY         VARCHAR2(26 CHAR),
    UPDATED_AT         TIMESTAMP WITH TIME ZONE,
    UPDATED_BY         VARCHAR2(26 CHAR)
);

CREATE TABLE PJ_MEMBER (
    PROJECT_ID  VARCHAR2(26 CHAR) NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    USER_ID     VARCHAR2(26 CHAR) NOT NULL REFERENCES CM_USER (USER_ID),
    ROLE_ID     VARCHAR2(30 CHAR) NOT NULL REFERENCES CM_ROLE (ROLE_ID),
    IN_DT       DATE,
    OUT_DT      DATE,
    PRIMARY KEY (PROJECT_ID, USER_ID)
);

-- ───────── As-Is 화면 분석 (AS) ─────────
CREATE TABLE AS_SYSTEM (
    SYSTEM_ID    VARCHAR2(26 CHAR)  PRIMARY KEY,
    PROJECT_ID   VARCHAR2(26 CHAR)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    CODE         VARCHAR2(30 CHAR)  NOT NULL,
    NAME         VARCHAR2(200 CHAR) NOT NULL,
    UI_TECH      VARCHAR2(300 CHAR),                      -- 콤마 구분
    SERVER_TECH  VARCHAR2(300 CHAR),
    DB_TYPE      VARCHAR2(30 CHAR),
    TEST_URL     VARCHAR2(500 CHAR),
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY   VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_SYSTEM UNIQUE (PROJECT_ID, CODE)
);

CREATE TABLE AS_COLLECT_RUN (
    RUN_ID             VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID          VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SEQ                NUMBER(10)      NOT NULL,
    RUN_KEY            VARCHAR2(100 CHAR),                -- manifest.runId
    COLLECTED_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
    UPLOADED_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    UPLOADED_BY        VARCHAR2(26 CHAR),
    MODEL_VERSION      VARCHAR2(20 CHAR),
    COLLECTOR_VERSION  VARCHAR2(50 CHAR),
    PACKAGE_FILE_ID    VARCHAR2(26 CHAR),
    REPORT_FILE_ID     VARCHAR2(26 CHAR),
    STATS_JSON         CLOB,
    DIFF_JSON          CLOB,
    BLOCKED_JSON       CLOB,
    FAILURES_JSON      CLOB,
    CONSTRAINT UQ_AS_RUN UNIQUE (SYSTEM_ID, SEQ)
);

CREATE TABLE AS_MENU (
    MENU_ID      VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    MENU_KEY     VARCHAR2(300 CHAR) NOT NULL,
    PARENT_KEY   VARCHAR2(300 CHAR),
    NAME         VARCHAR2(200 CHAR) NOT NULL,
    SORT_ORD     NUMBER(10) DEFAULT 0 NOT NULL,
    SCREEN_KEY   VARCHAR2(300 CHAR),
    URL          VARCHAR2(500 CHAR),
    LAST_RUN_ID  VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_MENU UNIQUE (SYSTEM_ID, MENU_KEY)
);

CREATE TABLE AS_SCREEN (
    SCREEN_ID    VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_KEY   VARCHAR2(300 CHAR) NOT NULL,
    SCREEN_CODE  VARCHAR2(100 CHAR) NOT NULL,
    NAME         VARCHAR2(200 CHAR) NOT NULL,
    KIND         VARCHAR2(20 CHAR)  DEFAULT 'page' NOT NULL,
    UI_TECH      VARCHAR2(30 CHAR),
    SOURCE_FILE  VARCHAR2(500 CHAR),
    URL          VARCHAR2(500 CHAR),
    LAST_RUN_ID  VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_SCREEN UNIQUE (SYSTEM_ID, SCREEN_KEY)
);

CREATE TABLE AS_CAPTURE (
    CAPTURE_ID    VARCHAR2(26 CHAR) PRIMARY KEY,
    SCREEN_ID     VARCHAR2(26 CHAR) NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    RUN_ID        VARCHAR2(26 CHAR) NOT NULL REFERENCES AS_COLLECT_RUN (RUN_ID),
    FILE_ID       VARCHAR2(26 CHAR) NOT NULL REFERENCES CM_FILE (FILE_ID),
    IDX           NUMBER(10)     NOT NULL,
    WIDTH         NUMBER(10)     NOT NULL,
    HEIGHT        NUMBER(10)     NOT NULL,
    STATE         VARCHAR2(100 CHAR),
    MASKED        NUMBER(1) DEFAULT 0 NOT NULL,
    COLLECTED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IX_AS_CAPTURE_SCREEN ON AS_CAPTURE (SCREEN_ID);

CREATE TABLE AS_ELEMENT (
    ELEMENT_ID     VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID      VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCREEN_ID      VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SCREEN (SCREEN_ID),
    ELEMENT_KEY    VARCHAR2(400 CHAR) NOT NULL,
    SEQ_NO         NUMBER(10)      NOT NULL,           -- 배지 번호 (최초 등록 순서로 고정)
    ELEMENT_CODE   VARCHAR2(200 CHAR) NOT NULL,
    NAME           VARCHAR2(200 CHAR),
    LABEL          VARCHAR2(300 CHAR),
    TYPE           VARCHAR2(20 CHAR)  NOT NULL,
    BOX_X          FLOAT(53),
    BOX_Y          FLOAT(53),
    BOX_W          FLOAT(53),
    BOX_H          FLOAT(53),
    CAPTURE_INDEX  NUMBER(10) DEFAULT 0 NOT NULL,
    BINDING        VARCHAR2(1000 CHAR),
    MATCHED        VARCHAR2(20 CHAR) DEFAULT 'full' NOT NULL,
    DANGER         NUMBER(1) DEFAULT 0 NOT NULL,
    MANUAL_YN      CHAR(1) DEFAULT 'N' NOT NULL,
    LAST_RUN_ID    VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_ELEMENT UNIQUE (SYSTEM_ID, ELEMENT_KEY)
);
CREATE INDEX IX_AS_ELEMENT_SCREEN ON AS_ELEMENT (SCREEN_ID);

-- 함수·API·SQL·SP·테이블 노드
CREATE TABLE AS_NODE (
    NODE_ID      VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    NODE_KEY     VARCHAR2(500 CHAR) NOT NULL,
    NODE_TYPE    VARCHAR2(10 CHAR)  NOT NULL,              -- FN / API / SQL / SP / TABLE
    NAME         VARCHAR2(500 CHAR),-- [oracle] 빈 값 허용(빈 문자열=NULL)
    LANG         VARCHAR2(20 CHAR),
    FILE_PATH    VARCHAR2(500 CHAR),
    LINE_START   NUMBER(10),
    LINE_END     NUMBER(10),
    SNIPPET      CLOB,
    COMMON       NUMBER(1) DEFAULT 0 NOT NULL,
    META_JSON    CLOB,                               -- 유형별 부가 정보(method/path/serviceId, sql kind 등)
    LAST_RUN_ID  VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_NODE UNIQUE (SYSTEM_ID, NODE_KEY)
);

CREATE TABLE AS_TABLE (
    TABLE_ID      VARCHAR2(26 CHAR) PRIMARY KEY REFERENCES AS_NODE (NODE_ID),
    SYSTEM_ID     VARCHAR2(26 CHAR) NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    SCHEMA_NM     VARCHAR2(100 CHAR),
    TABLE_NM      VARCHAR2(200 CHAR) NOT NULL,
    COMMENT_TXT   VARCHAR2(1000 CHAR),
    KIND          VARCHAR2(20 CHAR) DEFAULT 'table' NOT NULL,
    ROW_COUNT     NUMBER(19),
    SUBJECT_AREA  VARCHAR2(100 CHAR),
    INDEXES_JSON  CLOB
);

CREATE TABLE AS_COLUMN (
    TABLE_ID     VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_TABLE (TABLE_ID),
    COLUMN_NM    VARCHAR2(200 CHAR) NOT NULL,
    ORD          NUMBER(10)      NOT NULL,
    DATA_TYPE    VARCHAR2(100 CHAR) NOT NULL,
    NULLABLE     NUMBER(1),
    PK           NUMBER(1) DEFAULT 0 NOT NULL,
    DEFAULT_VAL  VARCHAR2(500 CHAR),
    COMMENT_TXT  VARCHAR2(1000 CHAR),
    PRIMARY KEY (TABLE_ID, COLUMN_NM)
);

CREATE TABLE AS_RELATION (
    REL_ID        VARCHAR2(26 CHAR)   PRIMARY KEY,
    SYSTEM_ID     VARCHAR2(26 CHAR)   NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    CHILD_KEY     VARCHAR2(500 CHAR)  NOT NULL,
    PARENT_KEY    VARCHAR2(500 CHAR)  NOT NULL,
    COLUMN_PAIRS  VARCHAR2(1000) NOT NULL,            -- JSON [["A","B"],...]
    KIND          VARCHAR2(10 CHAR)   NOT NULL,            -- fk / inferred
    EVIDENCE_CNT  NUMBER(10),
    CONFIDENCE    FLOAT(53),
    DECISION      VARCHAR2(10 CHAR) DEFAULT 'pending' NOT NULL,
    LAST_RUN_ID   VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_RELATION UNIQUE (SYSTEM_ID, CHILD_KEY, PARENT_KEY, COLUMN_PAIRS)
);

-- 모든 연결선 (요소→함수→API→서버→SQL→테이블, 화면 이동 등). FROM/TO 는 수집 키.
CREATE TABLE AS_EDGE (
    EDGE_ID      VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID    VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    FROM_KEY     VARCHAR2(500 CHAR) NOT NULL,
    TO_KEY       VARCHAR2(500 CHAR) NOT NULL,
    KIND         VARCHAR2(20 CHAR)  NOT NULL,
    EVENT        VARCHAR2(100 CHAR),-- [oracle] 빈 문자열=NULL 이라 NOT NULL·기본값 제외
    ORD          NUMBER(10),
    MODEL_SEQ    NUMBER(10),                            -- 수집 모델 내 순서 (ORD 없을 때 정렬 기준)
    COND         VARCHAR2(500 CHAR),
    CRUD         VARCHAR2(4 CHAR),
    COLUMNS_TXT  VARCHAR2(4000),
    SOURCE       VARCHAR2(10 CHAR)  NOT NULL,              -- static / dynamic / manual
    CONFIDENCE   FLOAT(53) NOT NULL,
    EVIDENCE     VARCHAR2(1000 CHAR),
    STATUS       VARCHAR2(10 CHAR) DEFAULT 'active' NOT NULL,
    LAST_RUN_ID  VARCHAR2(26 CHAR),
    CONSTRAINT UQ_AS_EDGE UNIQUE (SYSTEM_ID, FROM_KEY, TO_KEY, KIND, EVENT)
);
CREATE INDEX IX_AS_EDGE_FROM ON AS_EDGE (SYSTEM_ID, FROM_KEY);
CREATE INDEX IX_AS_EDGE_TO ON AS_EDGE (SYSTEM_ID, TO_KEY);

CREATE TABLE AS_ANALYSIS (
    SCREEN_ID     VARCHAR2(26 CHAR) PRIMARY KEY REFERENCES AS_SCREEN (SCREEN_ID),
    STATUS        VARCHAR2(10 CHAR) DEFAULT 'AUTO' NOT NULL,   -- AUTO / WORKING / REVIEW / DONE
    OWNER_ID      VARCHAR2(26 CHAR),
    REVIEWER_ID   VARCHAR2(26 CHAR),
    CONFIRMED_AT  TIMESTAMP WITH TIME ZONE,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY    VARCHAR2(26 CHAR)
);

CREATE TABLE AS_NOTE (
    NOTE_ID     VARCHAR2(26 CHAR)  PRIMARY KEY,
    SYSTEM_ID   VARCHAR2(26 CHAR)  NOT NULL REFERENCES AS_SYSTEM (SYSTEM_ID),
    TARGET_KEY  VARCHAR2(500 CHAR) NOT NULL,
    CONTENT     CLOB,-- [oracle] 빈 값 허용(빈 문자열=NULL)
    AUTHOR_ID   VARCHAR2(26 CHAR)  NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);

