-- PMS-X R3: SM 운영 (SR·SLA·장애·문제·변경·정기 작업·운영 자산·KB·월간 운영보고) (docs/13 명세)

-- ───────── SLA 정책 ─────────
CREATE TABLE SM_SLA_POLICY (
    POLICY_ID          VARCHAR2(26 CHAR)  PRIMARY KEY,
    PROJECT_ID         VARCHAR2(26 CHAR)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME               VARCHAR2(200 CHAR) NOT NULL,
    TYPES              VARCHAR2(200 CHAR),                 -- 콤마 구분, 비면 전체
    PRIORITIES         VARCHAR2(50 CHAR),                  -- 콤마 구분, 비면 전체
    RESPONSE_MIN       NUMBER(10)      NOT NULL,
    RESOLVE_MIN        NUMBER(10)      NOT NULL,
    BH_START           VARCHAR2(5 CHAR)   DEFAULT '09:00' NOT NULL,
    BH_END             VARCHAR2(5 CHAR)   DEFAULT '18:00' NOT NULL,
    BH_DAYS            VARCHAR2(20 CHAR)  DEFAULT '1,2,3,4,5' NOT NULL,   -- ISO 요일 1=월 … 7=일
    TWENTY_FOUR_SEVEN  NUMBER(1) DEFAULT 0 NOT NULL,
    ORD                NUMBER(10) DEFAULT 0 NOT NULL,
    CREATED_AT         TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT         TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IX_SM_SLA_POLICY_PROJECT ON SM_SLA_POLICY (PROJECT_ID, ORD);

-- ───────── SR ─────────
CREATE TABLE SM_SR (
    SR_ID          VARCHAR2(26 CHAR)  PRIMARY KEY,
    PROJECT_ID     VARCHAR2(26 CHAR)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    SR_NO          VARCHAR2(30 CHAR)  NOT NULL,
    TYPE           VARCHAR2(10 CHAR)  NOT NULL,
    PRIORITY       VARCHAR2(2 CHAR)   NOT NULL,
    TITLE          VARCHAR2(300 CHAR) NOT NULL,
    DESCRIPTION    CLOB,
    CHANNEL        VARCHAR2(10 CHAR)  NOT NULL,
    REQ_NAME       VARCHAR2(100 CHAR),-- [oracle] 빈 값 허용(빈 문자열=NULL)
    REQ_ORG        VARCHAR2(200 CHAR),
    REQ_CONTACT    VARCHAR2(200 CHAR),
    REQ_USER_ID    VARCHAR2(26 CHAR),
    STATUS         VARCHAR2(12 CHAR)  DEFAULT 'RECEIVED' NOT NULL,
    ASSIGNEE_ID    VARCHAR2(26 CHAR),
    SYSTEM_ID      VARCHAR2(26 CHAR),
    SCREEN_ID      VARCHAR2(26 CHAR),
    ELEMENT_ID     VARCHAR2(26 CHAR),
    POLICY_ID      VARCHAR2(26 CHAR),
    RESPONDED_AT   TIMESTAMP WITH TIME ZONE,
    RESOLVED_AT    TIMESTAMP WITH TIME ZONE,
    CLOSED_AT      TIMESTAMP WITH TIME ZONE,
    REJECT_REASON  VARCHAR2(1000 CHAR),
    NOTIFY_FLAGS   VARCHAR2(100 CHAR),                     -- SLA 알림 1회 발송 기록 (RESP_SOON,RESP_BREACH,RES_SOON,RES_BREACH)
    MESSAGE_ID     VARCHAR2(300 CHAR),                     -- 메일 접수 중복 방지
    ORIGIN_DEFECT_ID VARCHAR2(26 CHAR),                    -- SI→SM 인수인계로 생성된 경우 원래 결함
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY     VARCHAR2(26 CHAR),
    UPDATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_BY     VARCHAR2(26 CHAR),
    CONSTRAINT UQ_SM_SR_NO UNIQUE (PROJECT_ID, SR_NO)
);
CREATE INDEX IX_SM_SR_PROJECT ON SM_SR (PROJECT_ID, STATUS);
CREATE INDEX IX_SM_SR_SCREEN ON SM_SR (SCREEN_ID);
CREATE INDEX IX_SM_SR_CREATED ON SM_SR (PROJECT_ID, CREATED_AT);
CREATE INDEX IX_SM_SR_MESSAGE ON SM_SR (MESSAGE_ID);

-- SLA 시계 이벤트 (START / PAUSE / RESUME / STOP)
CREATE TABLE SM_SLA_EVENT (
    SR_ID     VARCHAR2(26 CHAR) NOT NULL,
    SEQ       NUMBER(10)     NOT NULL,
    EVENT     VARCHAR2(10 CHAR) NOT NULL,
    EVENT_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (SR_ID, SEQ)
);

CREATE TABLE SM_SR_COMMENT (
    COMMENT_ID  VARCHAR2(26 CHAR) PRIMARY KEY,
    SR_ID       VARCHAR2(26 CHAR) NOT NULL,
    CONTENT     CLOB,-- [oracle] 빈 값 허용(빈 문자열=NULL)
    INTERNAL    NUMBER(1) DEFAULT 0 NOT NULL,
    AUTHOR_ID   VARCHAR2(26 CHAR) NOT NULL,
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IX_SM_SR_COMMENT ON SM_SR_COMMENT (SR_ID, CREATED_AT);

-- ───────── 장애·문제·변경 ─────────
