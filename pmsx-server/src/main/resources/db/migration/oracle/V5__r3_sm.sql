-- ───────── 정기 작업·운영 자산·KB ─────────
CREATE TABLE SM_ROUTINE_JOB (
    JOB_ID          VARCHAR2(26 CHAR)  PRIMARY KEY,
    PROJECT_ID      VARCHAR2(26 CHAR)  NOT NULL REFERENCES PJ_PROJECT (PROJECT_ID),
    NAME            VARCHAR2(200 CHAR) NOT NULL,
    FREQ            VARCHAR2(10 CHAR)  NOT NULL,           -- DAILY / WEEKLY / MONTHLY
    DOW             VARCHAR2(20 CHAR),                     -- WEEKLY: ISO 요일 콤마 구분
    DAY_OF_MONTH    NUMBER(10),                         -- MONTHLY: 1~31 (말일 초과 시 말일)
    OWNER_ID        VARCHAR2(26 CHAR),
    CHECKLIST_JSON  CLOB,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE SM_ROUTINE_CHECK (
    JOB_ID    VARCHAR2(26 CHAR) NOT NULL,
    CHECK_DT  DATE        NOT NULL,
    DONE      NUMBER(1) DEFAULT 0 NOT NULL,
    DONE_BY   VARCHAR2(26 CHAR),
    DONE_AT   TIMESTAMP WITH TIME ZONE,
    NOTE      VARCHAR2(1000 CHAR),
    PRIMARY KEY (JOB_ID, CHECK_DT)
);

CREATE TABLE SM_OPS_ASSET (
    ASSET_ID        VARCHAR2(26 CHAR)  PRIMARY KEY,
