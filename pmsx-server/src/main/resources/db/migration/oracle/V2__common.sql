-- ───────── 사용자 보강 (비밀번호 정책·잠금·LDAP) ─────────
ALTER TABLE CM_USER ADD (EMAIL VARCHAR2(200 CHAR));
ALTER TABLE CM_USER ADD (LOCKED NUMBER(1) DEFAULT 0 NOT NULL);
ALTER TABLE CM_USER ADD (FAIL_COUNT NUMBER(10) DEFAULT 0 NOT NULL);
ALTER TABLE CM_USER ADD (LAST_LOGIN_AT TIMESTAMP WITH TIME ZONE);
ALTER TABLE CM_USER ADD (PASSWORD_CHANGED_AT TIMESTAMP WITH TIME ZONE);

CREATE TABLE CM_PASSWORD_HISTORY (
    USER_ID        VARCHAR2(26 CHAR)  NOT NULL REFERENCES CM_USER (USER_ID),
    PASSWORD_HASH  VARCHAR2(100 CHAR) NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IX_CM_PWHIST_USER ON CM_PASSWORD_HISTORY (USER_ID, CREATED_AT);

-- ───────── 공통코드·용어 ─────────
CREATE TABLE CM_CODE_GROUP (
    GROUP_CODE   VARCHAR2(50 CHAR)   PRIMARY KEY,
    NAME         VARCHAR2(100 CHAR)  NOT NULL,
    DESCRIPTION  VARCHAR2(500 CHAR),
    SYSTEM_YN    NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY   VARCHAR2(26 CHAR),
    UPDATED_AT   TIMESTAMP WITH TIME ZONE,
    UPDATED_BY   VARCHAR2(26 CHAR)
);

CREATE TABLE CM_CODE (
    GROUP_CODE  VARCHAR2(50 CHAR)  NOT NULL REFERENCES CM_CODE_GROUP (GROUP_CODE),
    CODE        VARCHAR2(50 CHAR)  NOT NULL,
    NAME        VARCHAR2(200 CHAR) NOT NULL,
    SORT_ORD    NUMBER(10) DEFAULT 0 NOT NULL,
    USE_YN      NUMBER(1) DEFAULT 1 NOT NULL,
    ATTR1       VARCHAR2(200 CHAR),
    ATTR2       VARCHAR2(200 CHAR),
    PRIMARY KEY (GROUP_CODE, CODE)
);

CREATE TABLE CM_TERM (
    TERM_ID     VARCHAR2(26 CHAR)   PRIMARY KEY,
    TERM        VARCHAR2(200 CHAR)  NOT NULL,
    ABBR        VARCHAR2(100 CHAR),
    DEFINITION  VARCHAR2(4000),-- [oracle] 빈 값 허용(빈 문자열=NULL)
    TERM_DOMAIN VARCHAR2(100 CHAR),
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY  VARCHAR2(26 CHAR),
    UPDATED_AT  TIMESTAMP WITH TIME ZONE,
    UPDATED_BY  VARCHAR2(26 CHAR)
);
CREATE INDEX IX_CM_TERM_TERM ON CM_TERM (TERM);

-- ───────── 첨부 (대상별 파일, 같은 이름 = 새 버전) ─────────
CREATE TABLE CM_ATTACH (
    ATTACH_ID       VARCHAR2(26 CHAR)  PRIMARY KEY,
    TARGET_TYPE     VARCHAR2(50 CHAR)  NOT NULL,
    TARGET_ID       VARCHAR2(100 CHAR) NOT NULL,
    NAME            VARCHAR2(300 CHAR) NOT NULL,
    LATEST_VERSION  NUMBER(10)      NOT NULL,
    DELETED         NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY      VARCHAR2(26 CHAR),
    UPDATED_AT      TIMESTAMP WITH TIME ZONE,
    UPDATED_BY      VARCHAR2(26 CHAR)
);
CREATE INDEX IX_CM_ATTACH_TARGET ON CM_ATTACH (TARGET_TYPE, TARGET_ID);

CREATE TABLE CM_ATTACH_VERSION (
    ATTACH_ID   VARCHAR2(26 CHAR) NOT NULL REFERENCES CM_ATTACH (ATTACH_ID),
    VERSION     NUMBER(10)     NOT NULL,
    FILE_ID     VARCHAR2(26 CHAR) NOT NULL REFERENCES CM_FILE (FILE_ID),
    CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY  VARCHAR2(26 CHAR),
    PRIMARY KEY (ATTACH_ID, VERSION)
);

-- ───────── 엑셀 템플릿 ─────────
CREATE TABLE CM_EXCEL_TEMPLATE (
    TEMPLATE_ID   VARCHAR2(26 CHAR)   PRIMARY KEY,
    NAME          VARCHAR2(200 CHAR)  NOT NULL,
    DATASET_ID    VARCHAR2(50 CHAR)   NOT NULL,
    FILE_ID       VARCHAR2(26 CHAR)   NOT NULL REFERENCES CM_FILE (FILE_ID),
    MAPPING_JSON  VARCHAR2(4000) NOT NULL,
    CREATED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY    VARCHAR2(26 CHAR),
    UPDATED_AT    TIMESTAMP WITH TIME ZONE,
    UPDATED_BY    VARCHAR2(26 CHAR)
);

-- ───────── 감사 로그 ─────────
CREATE TABLE CM_AUDIT_LOG (
    LOG_ID      VARCHAR2(26 CHAR)   PRIMARY KEY,
    LOG_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
    USER_ID     VARCHAR2(26 CHAR),
    LOGIN_ID    VARCHAR2(50 CHAR),
    ACTION      VARCHAR2(20 CHAR)   NOT NULL,
    TARGET      VARCHAR2(500 CHAR),
    DETAIL      VARCHAR2(4000),
    IP          VARCHAR2(64 CHAR),
    PROJECT_ID  VARCHAR2(26 CHAR)
);
CREATE INDEX IX_CM_AUDIT_AT ON CM_AUDIT_LOG (LOG_AT);
CREATE INDEX IX_CM_AUDIT_USER ON CM_AUDIT_LOG (USER_ID, LOG_AT);

-- ───────── 라이선스 (적용된 키 1건) ─────────
CREATE TABLE CM_LICENSE (
    LICENSE_ID   VARCHAR2(10 CHAR)   PRIMARY KEY,          -- 'CURRENT'
    LICENSE_KEY  VARCHAR2(4000) NOT NULL,
    APPLIED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    APPLIED_BY   VARCHAR2(26 CHAR)
);

